package app_test

//go:generate go run ../../../cmd/volt gen .

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Piechutowski/volt/gen/router"
	"github.com/Piechutowski/volt/internal/disk"
	"github.com/Piechutowski/volt/lang"
)

// TestGeneratedFilesCurrent regenerates the routes package through the
// path volt gen takes and proves the committed router, handlers, paths,
// route table and client are byte-identical, carry the marker, and that
// the package checks clean and vets with the one streamcount report of
// the CSV export (spec §requests-and-responses, docs/lint.md).
// On failure: go generate ./examples/voltmeter/app
func TestGeneratedFilesCurrent(t *testing.T) {
	root, err := lang.FindRoot(disk.Source{}, ".")
	if err != nil {
		t.Fatal(err)
	}
	pr, err := lang.LoadDirs(disk.Source{}, root, []string{"."}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if diags := lang.Check(pr); len(diags) > 0 {
		t.Fatalf("check: %v", diags)
	}
	diags := lang.Vet(pr)
	if len(diags) != 1 || diags[0].Code != "vet/streamcount" || !strings.Contains(diags[0].String(), "report.go") {
		t.Errorf("vet: want the one streamcount of report.go, got %v", diags)
	}
	pkg := pr.PackageAt(".")
	if pkg == nil || !pkg.HasRouting() {
		t.Fatal("app is not loaded as a routes package")
	}
	files, err := router.Generate(pkg, router.Options{Source: "package " + pkg.Path})
	if err != nil {
		t.Fatal(err)
	}
	for name, want := range files {
		got, err := os.ReadFile(name)
		if err != nil || !bytes.Equal(got, want) {
			t.Errorf("%s drifted from the generator (%v); run go generate ./examples/voltmeter/app", name, err)
		}
		if !bytes.HasPrefix(want, []byte("// Code generated by volt gen")) {
			t.Errorf("%s lacks the generated marker", name)
		}
	}
	written, err := filepath.Glob("volt_*")
	if err != nil {
		t.Fatal(err)
	}
	clients, err := filepath.Glob(filepath.Join("client", "volt_*"))
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range append(written, clients...) {
		if _, ok := files[name]; !ok {
			t.Errorf("%s is no longer generated", name)
		}
	}
}
