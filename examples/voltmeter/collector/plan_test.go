func TestUploadOf(t *testing.T) {
	m := perfsweep.Machine{CPU: "Bench CPU", Cores: 4, MemoryGB: 7.5, OS: "linux", Arch: "arm64", Go: "go1.27.1", Commit: "ABC1234+dirty"}
	rows := []perfsweep.Row{
		{Tables: 2, Phase: "load", WallMS: 1.5, AllocMB: 0.25, HeapMB: 3, Allocs: 1200, SourceKB: 0.75, Profile: "load_002.prof"},
		{Tables: 2, Phase: "generate", WallMS: 4, AllocMB: 1, HeapMB: 4, Allocs: 9000, OutputMB: 0.1, SourceKB: 0.75},
	}
	ks := []perfsweep.Keystroke{{Tables: 2, MSPerOp: 0.5, MBPerOp: 0.02, AllocsPerOp: 77}}
	u, err := collector.UploadOf(m, rows, ks, "nightly", "a note", 3)
	if err != nil {
		t.Fatal(err)
	}
	want := app.Upload{
		Commit: "abc1234", Dirty: true, Tag: "nightly", Note: "a note", Baseline: 3,
		Machine: app.UploadMachine{CPU: "Bench CPU", Cores: 4, MemoryGB: 7.5, OS: "linux", Arch: "arm64", Go: "go1.27.1"},
		Phases: []app.UploadPhase{
			{Phase: db.PhaseLoad, Tables: 2, WallMS: 1.5, AllocMB: 0.25, HeapMB: 3, Allocs: 1200, SourceKB: 0.75},
			{Phase: db.PhaseGenerate, Tables: 2, WallMS: 4, AllocMB: 1, HeapMB: 4, Allocs: 9000, OutputMB: 0.1, SourceKB: 0.75},
		},
		Keystrokes: []app.UploadKeystroke{{Tables: 2, MSPerOp: 0.5, MBPerOp: 0.02, AllocsPerOp: 77}},
	}
	if !reflect.DeepEqual(u, want) {
		t.Errorf("UploadOf =\n%+v\nwant\n%+v", u, want)
	}
	m.Commit = "abc1234"
	if u, _ := collector.UploadOf(m, nil, nil, "", "", 0); u.Dirty || u.Commit != "abc1234" {
		t.Errorf("a clean tree: %+v", u)
	}
	m.Commit = "unknown"
	if _, err := collector.UploadOf(m, rows, nil, "", "", 0); err == nil || !strings.Contains(err.Error(), `"unknown"`) {
		t.Errorf("an unread commit: %v", err)
	}
}

func TestGitOutputParse(t *testing.T) {
	log := "aaaa1111\x1fAda Writer\x1f2026-10-01T12:30:00+02:00\x1fAdd the metrics table\x1e\n" +
		"bbbb2222\x1fBo Reader\x1f2026-09-30T08:00:00Z\x1fSplit\x1fnothing\x1e\n"
	if _, err := collector.CommitsParse([]byte(log)); err == nil {
		t.Error("a subject holding the unit separator is not a record of four fields")
	}
	cs, err := collector.CommitsParse([]byte(log[:strings.Index(log, "bbbb")]))
	if err != nil {
		t.Fatal(err)
	}
	at := time.Date(2026, 10, 1, 10, 30, 0, 0, time.UTC)
	if len(cs) != 1 || cs[0].SHA != "aaaa1111" || cs[0].Author != "Ada Writer" || cs[0].Subject != "Add the metrics table" || !cs[0].At.Equal(at) || cs[0].At.Location() != time.UTC {
		t.Errorf("CommitsParse = %+v", cs)
	}

	tree := "100644 blob 1111\titest/blog/db/schema.volt\x00160000 commit 2222\tvendor/mod\x00100644 blob 3333\titest/blog/db/a b.go\x00"
	blobs, err := collector.TreeParse([]byte(tree))
	if err != nil {
		t.Fatal(err)
	}
	if want := []collector.Blob{{Object: "1111", Path: "itest/blog/db/schema.volt"}, {Object: "3333", Path: "itest/blog/db/a b.go"}}; !slices.Equal(blobs, want) {
		t.Errorf("TreeParse = %+v", blobs)
	}

	batch := "1111 blob 6\nline\n\n\n3333 blob 0\n\n4444 blob 3\nabc\n"
	objs, err := collector.BatchParse([]byte(batch))
	if err != nil {
		t.Fatal(err)
	}
	if len(objs) != 3 || string(objs[0]) != "line\n\n" || len(objs[1]) != 0 || string(objs[2]) != "abc" {
		t.Errorf("BatchParse = %q", objs)
	}
	if _, err := collector.BatchParse([]byte("1111 blob 9\nshort\n")); err == nil {
		t.Error("an object cut short parses")
	}
	if _, err := collector.BatchParse([]byte("1111 missing\n")); err == nil {
		t.Error("a missing object parses")
	}
}

func TestLinesCount(t *testing.T) {
	files := []collector.File{
		{Path: "itest/blog/db/schema.volt", Data: []byte("table posts {\n  id int [pk]\n}\n")},
		{Path: "itest/blog/db/volt_models.go", Data: []byte("// Code generated by volt gen from package db. DO NOT EDIT.\n\npackage db\n")},
		{Path: "itest/blog/db/checks.go", Data: []byte("package db\n\nfunc ok() {}")},
		{Path: "itest/blog/db/checks_test.go", Data: []byte("package db\n")},
		{Path: "itest/blog/db/look.go", Data: []byte("package db\n\n// Code generated is how this one starts. DO NOT EDIT.\nvar x = 1\n")},
		{Path: "itest/blog/db/volt_schema.sql", Data: []byte("-- Code generated by volt gen. DO NOT EDIT.\nCREATE TABLE posts();\n")},
		{Path: "itest/blog/empty.go", Data: nil},
	}
	got := collector.LinesCount("itest/blog", files)
	if want := (app.ThesisCount{Fixture: "itest/blog", VoltLines: 3, GenLines: 3, HandLines: 3 + 1 + 4}); got != want {
		t.Errorf("LinesCount = %+v, want %+v", got, want)
	}

	commits := []app.ThesisCommit{{SHA: "aaaa"}, {SHA: "bbbb"}}
	fixtures := []string{"itest/blog", "examples/voltmeter/"}
	up, err := collector.ThesisOf(commits, fixtures, [][]collector.File{
		{files[0], {Path: "examples/voltmeter/db/schema.volt", Data: []byte("x\ny\n")}, {Path: "examples/voltmeterx/a.volt", Data: []byte("z\n")}},
		{files[2]},
	})
	if err != nil {
		t.Fatal(err)
	}
	want := app.ThesisUpload{Commits: []app.ThesisCommit{
		{SHA: "aaaa", Counts: []app.ThesisCount{{Fixture: "itest/blog", VoltLines: 3}, {Fixture: "examples/voltmeter/", VoltLines: 2}}},
		{SHA: "bbbb", Counts: []app.ThesisCount{{Fixture: "itest/blog", HandLines: 3}}},
	}}
	if !reflect.DeepEqual(up, want) {
		t.Errorf("ThesisOf =\n%+v\nwant\n%+v", up, want)
	}
	if _, err := collector.ThesisOf(commits, fixtures, nil); err == nil {
		t.Error("ThesisOf took fewer file lists than commits")
	}
}

func TestReadCallsCoverTheSafeRoutes(t *testing.T) {
	calls := collector.ReadCalls(collector.Targets{Run: 7, Machine: 2, Tag: "nightly", Fixture: "itest/blog", Tables: 4, Board: 3, Budget: 5})
	got := map[string]collector.Call{}
	for _, c := range calls {
		if _, dup := got[c.Route]; dup {
			t.Errorf("%s is called twice", c.Route)
		}
		got[c.Route] = c
		if !strings.HasPrefix(c.Route, c.Method+" ") {
			t.Errorf("%s is asked with %s", c.Route, c.Method)
		}
	}
	want := map[string]bool{}
	for _, r := range app.Table {
		method := r.Method
		switch method {
		case "":
			method = "GET"
		case "GET", "HEAD", "OPTIONS":
		default:
			continue
		}
		key := method + " " + r.Pattern
		if _, ok := collector.ReadCallsExcluded[key]; ok {
			continue
		}
		want[key] = true
		if _, ok := got[key]; !ok {
			t.Errorf("no call times %s", key)
		}
	}
	for key := range got {
		if !want[key] {
			t.Errorf("%s is no read route of app.Table", key)
		}
	}
	for key := range collector.ReadCallsExcluded {
		if !slices.ContainsFunc(app.Table, func(r volt.Route) bool { return r.Method+" "+r.Pattern == key }) {
			t.Errorf("excluded %s is no route", key)
		}
	}
	for route, path := range map[string]string{
		"GET /api/runs/{id}":             "/api/runs/7",
		"GET /api/machines/{id}":         "/api/machines/2",
		"GET /api/tags/{slug}":           "/api/tags/nightly",
		"GET /api/budgets/{id}":          "/api/budgets/5",
		"GET /api/me/dashboards/{board}": "/api/me/dashboards/3",
		"GET /api/thesis":                "/api/thesis?fixture=itest%2Fblog",
		"GET /api/trend/vet":             "/api/trend/vet?tables=4",
		"GET /api/phases/load":           "/api/phases/load?run=7",
		"HEAD /reports/runs/{id}":        "/reports/runs/7",
	} {
		if got[route].Path != path {
			t.Errorf("%s asks %q, want %q", route, got[route].Path, path)
		}
	}
}

func TestSamples(t *testing.T) {
	start := time.UnixMilli(1_790_000_000_123)
	s := collector.SampleOf(collector.Call{Method: "GET", Route: "GET /api/fleet"}, 200, start, 1500*time.Microsecond)
	if s != (app.SampleTimed{Route: "GET /api/fleet", Status: 200, MS: 1.5, At: 1_790_000_000_123}) {
		t.Errorf("SampleOf = %+v", s)
	}
	var many []app.SampleTimed
	for i := range 5 {
		many = append(many, app.SampleTimed{Route: fmt.Sprint(i)})
	}
	bs := collector.SamplesBatched(many, 2)
	if len(bs) != 3 || len(bs[0].Samples) != 2 || len(bs[2].Samples) != 1 || bs[2].Samples[0].Route != "4" {
		t.Errorf("SamplesBatched = %+v", bs)
	}
	if collector.SamplesBatched(nil, 2) != nil {
		t.Error("no sample is no batch")
	}
}

// TestBuildCheck proves a binary built at another commit, or from a tree
// whose modified state differs, is refused, and a binary without
// version control stamps, as go test and go run build, passes.
func TestBuildCheck(t *testing.T) {
	const head = "996b13bda003f8bb30eacfa7f17f7d4a39e74165"
	stamp := func(rev, modified string) []debug.BuildSetting {
		return []debug.BuildSetting{{Key: "vcs", Value: "git"}, {Key: "vcs.revision", Value: rev}, {Key: "vcs.modified", Value: modified}}
	}
	cases := []struct {
		name     string
		settings []debug.BuildSetting
		dirty    bool
		refused  string
	}{
		{"unstamped", nil, false, ""},
		{"unstamped dirty", []debug.BuildSetting{{Key: "-compiler", Value: "gc"}}, true, ""},
		{"same commit", stamp(head, "false"), false, ""},
		{"same dirty commit", stamp(head, "true"), true, ""},
		{"stale binary", stamp("d41128b0000000000000000000000000000000000", "false"), false, "built at d41128b"},
		{"binary of a modified tree", stamp(head, "true"), false, "modified state"},
		{"clean binary over a dirty tree", stamp(head, "false"), true, "modified state"},
	}
	for _, c := range cases {
		err := collector.BuildCheck(c.settings, head, c.dirty)
		if c.refused == "" && err != nil {
			t.Errorf("%s refused: %v", c.name, err)
		}
		if c.refused != "" && (err == nil || !strings.Contains(err.Error(), c.refused)) {
			t.Errorf("%s = %v, want a refusal naming %q", c.name, err, c.refused)
		}
	}
}
