// Package sqlite generates SQLite DDL (nao_schema.sql) from a checked
// schema file: CREATE TABLE per table, CREATE INDEX per index, and
// INSERT statements from records. Dialect decisions follow docs/spec.md
// §mapping-to-sqlite-ddl.
package sqlite

import (
	"fmt"
	"strings"

	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/lang/token"
)

// Options configures generation.
type Options struct {
	// Source is the name of the schema input, recorded in the header.
	Source string
}

// Generate renders the schema file for one checked schema file.
func Generate(f *ast.File, info *check.Info, opts Options) ([]byte, error) {
	g := &generator{f: f, info: info, opts: opts}
	if err := g.run(); err != nil {
		return nil, err
	}
	return []byte(g.out.String()), nil
}

type generator struct {
	f    *ast.File
	info *check.Info
	opts Options

	out strings.Builder
}

func (g *generator) run() error {
	fmt.Fprintf(&g.out, "-- Code generated by nao gen sqlite from %s; DO NOT EDIT.\n", g.opts.Source)
	if note := projectNote(g.f); note != "" {
		g.out.WriteString("--\n")
		commentWrite(&g.out, "", note)
	}
	g.out.WriteString("\nPRAGMA foreign_keys = ON;\n")

	for _, ti := range g.info.Tables {
		if err := g.tableEmit(ti); err != nil {
			return err
		}
	}

	for _, ti := range g.info.Tables {
		for _, item := range ti.Decl.Body {
			if r, ok := item.(*ast.Records); ok {
				if err := g.insertsEmit(ti, r); err != nil {
					return err
				}
			}
		}
	}
	for _, d := range g.f.Decls {
		if r, ok := d.(*ast.Records); ok && r.Table != nil {
			ti := g.info.Table(r.Table.Name())
			if ti == nil {
				return fmt.Errorf("records target %q not found", r.Table.Name())
			}
			if err := g.insertsEmit(ti, r); err != nil {
				return err
			}
		}
	}
	return nil
}

func (g *generator) tableEmit(ti *check.TableInfo) error {
	name := ti.Key

	g.out.WriteString("\n")
	if note := tableNote(ti.Decl); note != "" {
		commentWrite(&g.out, "", note)
	}
	fmt.Fprintf(&g.out, "CREATE TABLE %s (\n", identQuote(name))

	var pkCols []string
	for _, cd := range ti.PK() {
		pkCols = append(pkCols, cd.Col.Name.Name())
	}

	var lines []string
	for _, cd := range ti.Columns {
		line, err := g.columnDef(ti, cd, pkCols)
		if err != nil {
			return fmt.Errorf("table %s: %w", name, err)
		}
		if note := settingNote(cd.Col.Settings); note != "" {
			var b strings.Builder
			commentWrite(&b, "  ", note)
			line = b.String() + line
		}
		lines = append(lines, line)
	}

	if len(pkCols) > 1 {
		lines = append(lines, "  PRIMARY KEY ("+quotedJoin(pkCols)+")")
	}

	for _, r := range g.info.Refs {
		if r.FK.Table != ti || r.Target.Table == nil {
			continue
		}
		line := "  FOREIGN KEY (" + quotedJoin(r.FK.Columns) + ") REFERENCES " +
			identQuote(r.Target.Table.Key) + " (" + quotedJoin(r.Target.Columns) + ")"
		if a := refAction(r, "delete"); a != "" {
			line += " ON DELETE " + a
		}
		if a := refAction(r, "update"); a != "" {
			line += " ON UPDATE " + a
		}
		lines = append(lines, line)
	}

	g.out.WriteString(strings.Join(lines, ",\n"))
	g.out.WriteString("\n);\n")

	return g.indexesEmit(ti)
}

func (g *generator) columnDef(ti *check.TableInfo, cd *check.ColumnDef, pkCols []string) (string, error) {
	sqlType, err := g.typeResolve(cd)
	if err != nil {
		return "", fmt.Errorf("column %q: %w", cd.Col.Name.Name(), err)
	}
	return columnLine(cd.Col, sqlType, pkCols)
}

// columnLine renders one column definition of a CREATE TABLE (spec
// §mapping-to-sqlite-ddl): PRIMARY KEY on the one column of a
// single-column key, the rowid alias for int [pk, increment], NOT NULL
// for a column without null, the rowid alias excepted, and DEFAULT.
// pkCols are the key's columns in order; a composite key is the
// table's PRIMARY KEY constraint, and unique and index are CREATE
// INDEX statements, neither on the column.
func columnLine(col *ast.Column, sqlType string, pkCols []string) (string, error) {
	colName := col.Name.Name()
	singlePK := col.Settings.Get("pk") != nil && len(pkCols) == 1
	rowidAlias := singlePK && sqlType == "INTEGER" && col.Settings.Get("increment") != nil

	parts := []string{"  " + identQuote(colName), sqlType}
	if singlePK {
		parts = append(parts, "PRIMARY KEY")
	}
	if !rowidAlias && !isNullable(col) {
		parts = append(parts, "NOT NULL")
	}
	if s := col.Settings.Get("default"); s != nil {
		def, err := defaultSQL(s.Value)
		if err != nil {
			return "", fmt.Errorf("column %q: %w", colName, err)
		}
		parts = append(parts, "DEFAULT "+def)
	}
	return strings.Join(parts, " "), nil
}

func (g *generator) indexesEmit(ti *check.TableInfo) error {
	cols := make([]*ast.Column, len(ti.Columns))
	for i, cd := range ti.Columns {
		cols[i] = cd.Col
	}
	stmts, err := indexStatements(ti.Key, cols, ti.Indexes)
	if err != nil {
		return err
	}
	for _, s := range stmts {
		g.out.WriteString(s + ";\n")
	}
	return nil
}

// indexStatements renders the CREATE INDEX statements of a table,
// without trailing semicolons (spec §indexes, §mapping-to-sqlite-ddl):
// first the index of every column that carries unique or index, in
// column order, then the indexes of its Indexes blocks in order. Two
// indexes of one name are an error, which the checker reports first.
func indexStatements(table string, cols []*ast.Column, indexes []*ast.Index) ([]string, error) {
	all := make([]*ast.Index, 0, len(cols)+len(indexes))
	for _, col := range cols {
		if ix := check.ColumnIndex(col); ix != nil {
			all = append(all, ix)
		}
	}
	all = append(all, indexes...)
	out := make([]string, 0, len(all))
	used := map[string]bool{}
	for _, ix := range all {
		name, err := IndexName(table, ix)
		if err != nil {
			return nil, fmt.Errorf("table %s: %w", table, err)
		}
		if used[name] {
			return nil, fmt.Errorf("table %s: duplicate index name %q (§indexes)", table, name)
		}
		used[name] = true
		out = append(out, IndexDDL(table, name, ix))
	}
	return out, nil
}

// IndexName is the SQLite name of an index (spec §indexes,
// §mapping-to-sqlite-ddl): name: when given, else idx_<table>_<col>
// [_<col>...] over a key of columns; an expression key without name:
// is an error.
func IndexName(table string, ix *ast.Index) (string, error) {
	name, ok := check.IndexName(table, ix)
	if !ok {
		return "", fmt.Errorf("index on %s has an expression in its key and no name: (§indexes)", table)
	}
	return name, nil
}

// IndexDDL renders one CREATE INDEX statement without the trailing
// semicolon (spec §mapping-to-sqlite-ddl): UNIQUE for unique, the key's
// columns quoted and its expressions parenthesized, WHERE for a partial
// index.
func IndexDDL(table, name string, ix *ast.Index) string {
	stmt := "CREATE INDEX"
	if ix.Settings.Get("unique") != nil {
		stmt = "CREATE UNIQUE INDEX"
	}
	var keys []string
	for _, atom := range ix.Key {
		switch a := atom.(type) {
		case *ast.Ident:
			keys = append(keys, identQuote(a.Name()))
		case *ast.FuncExpr:
			keys = append(keys, "("+a.Text()+")")
		}
	}
	where := ""
	if s := ix.Settings.Get("where"); s != nil {
		if fe, ok := s.Value.(*ast.FuncExpr); ok {
			where = " WHERE " + fe.Text()
		}
	}
	return fmt.Sprintf("%s %s ON %s (%s)%s", stmt, identQuote(name), identQuote(table), strings.Join(keys, ", "), where)
}

func (g *generator) insertsEmit(ti *check.TableInfo, r *ast.Records) error {
	cols := make([]string, 0)
	if r.HasColumns {
		for _, c := range r.Columns {
			cols = append(cols, c.Name())
		}
	} else {
		for _, cd := range ti.Columns {
			cols = append(cols, cd.Col.Name.Name())
		}
	}
	if len(r.Rows) == 0 {
		return nil
	}
	fmt.Fprintf(&g.out, "\nINSERT INTO %s (%s) VALUES\n", identQuote(ti.Key), quotedJoin(cols))
	var rows []string
	for _, row := range r.Rows {
		var vals []string
		for _, v := range row.Values {
			sql, err := valueSQL(v)
			if err != nil {
				return fmt.Errorf("records for %s: %w", ti.Key, err)
			}
			vals = append(vals, sql)
		}
		rows = append(rows, "  ("+strings.Join(vals, ", ")+")")
	}
	g.out.WriteString(strings.Join(rows, ",\n"))
	g.out.WriteString(";\n")
	return nil
}

func defaultSQL(v ast.Node) (string, error) {
	switch v := v.(type) {
	case *ast.FuncExpr:
		return "(" + v.Text() + ")", nil
	default:
		return valueSQL(v)
	}
}

func valueSQL(v ast.Node) (string, error) {
	switch v := v.(type) {
	case *ast.BasicLit:
		if v.Tok.Kind == token.STRING {
			return stringQuote(v.Tok.Val), nil
		}
		return v.Tok.Val, nil
	case *ast.NegNumber:
		return "-" + v.Num.Tok.Val, nil
	case *ast.FuncExpr:
		return v.Tok.Val, nil
	case *ast.Ident:
		switch v.Name() {
		case "true":
			return "1", nil
		case "false":
			return "0", nil
		case "null":
			return "NULL", nil
		}
	}
	return "", fmt.Errorf("unsupported value at %s", v.Pos())
}

func isNullable(col *ast.Column) bool { return col.Settings.Get("null") != nil }

func refAction(r *check.RefInfo, kind string) string {
	ref, ok := r.Node.(*ast.Ref)
	if !ok {
		return ""
	}
	return actionSQL(ref.Settings, kind)
}

func actionSQL(sl *ast.SettingList, kind string) string {
	s := sl.Get(kind)
	if s == nil {
		return ""
	}
	if v, ok := s.Value.(*ast.Ident); ok {
		return strings.ToUpper(strings.ReplaceAll(v.Name(), "_", " "))
	}
	return ""
}

func projectNote(f *ast.File) string {
	for _, d := range f.Decls {
		if p, ok := d.(*ast.Project); ok {
			return settingNote(p.Settings)
		}
	}
	return ""
}

func tableNote(t *ast.Table) string { return settingNote(t.Settings) }

func settingNote(sl *ast.SettingList) string { return settingString(sl, "note") }

func settingString(sl *ast.SettingList, name string) string {
	s := sl.Get(name)
	if s == nil {
		return ""
	}
	if lit, ok := s.Value.(*ast.BasicLit); ok {
		return lit.Tok.Val
	}
	return ""
}

func commentWrite(b *strings.Builder, indent, text string) {
	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		if strings.TrimSpace(line) == "" {
			b.WriteString(indent + "--\n")
			continue
		}
		b.WriteString(indent + "-- " + line + "\n")
	}
}

// Ident quotes an identifier for SQLite the way the DDL generator does
// (spec §selects-over-groups).
func Ident(name string) string { return identQuote(name) }
