// CRUD generation (volt_queries.go): the static query surface as values,
// one function per statement returning the rt effect the runner
// performs (docs/spec.md §generated-query-surface, §predicates).
package golang

import (
	"fmt"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/naming"
)

// GenerateQueries renders the queries file for one checked schema file.
func GenerateQueries(f *ast.File, info *check.Info, opts Options) ([]byte, error) {
	return Queries(naming.PlanBuild(f, info), opts)
}

// Queries renders the queries file (volt_queries.go) for the planned
// package (spec §generated-query-surface).
func Queries(pl *naming.Plan, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if err := pl.Err(); err != nil {
		return nil, err
	}
	e := &queryEmitter{tables: pl.Tables(), opts: opts}
	e.run()
	if e.err != nil {
		return nil, e.err
	}
	return align.Finish(e.out.String()), nil
}

func scanTarget(f *naming.Field) string {
	switch {
	case f.PlainBytes():
		return "(*rt.Bytes)(&voltV." + f.GoField + ")"
	case f.Kinded && !f.Nullable:
		return "(*" + f.Storage + ")(&voltV." + f.GoField + ")"
	case f.GoType == "time.Time":
		return "(*rt.Time)(&voltV." + f.GoField + ")"
	}
	return "&voltV." + f.GoField
}

type queryEmitter struct {
	tables []*naming.Table
	opts   Options
	out    strings.Builder
	body   strings.Builder
	err    error

	needImports map[string]bool
}

func (e *queryEmitter) fail(t *naming.Table, what string, err error) {
	if e.err == nil {
		e.err = fmt.Errorf("table %s: %s: %w", t.Info.Decl.Name.Name(), what, err)
	}
}

func (e *queryEmitter) run() {
	e.needImports = map[string]bool{}
	e.body.Grow(fieldCount(e.tables)*100 + len(e.tables)*1200)
	for _, t := range e.tables {
		e.tableEmit(t)
	}
	e.header()
	e.out.Grow(e.body.Len())
	e.out.WriteString(e.body.String())
}

func (e *queryEmitter) header() {
	fmt.Fprintf(&e.out, "// Code generated by volt gen from %s. DO NOT EDIT.\n", e.opts.Source)
	e.out.WriteString("\n")
	fmt.Fprintf(&e.out, "package %s\n\n", e.opts.Package)

	imports := map[string]bool{rtImport: true}
	for imp := range e.needImports {
		imports[imp] = true
	}
	e.out.WriteString("import (\n")
	for _, p := range importKeysSort(imports) {
		fmt.Fprintf(&e.out, "\t%s\n", importDecl(p))
	}
	e.out.WriteString(")\n\n")
}

func (e *queryEmitter) tableEmit(t *naming.Table) {
	if len(t.Fields) == 0 {
		return
	}
	if len(t.PK) > 0 {
		for _, f := range t.PK {
			e.needImports[f.Imp] = true
		}
	}
	for _, f := range t.UniqueFields() {
		e.needImports[f.Imp] = true
	}
	delete(e.needImports, "")

	if len(t.PK) > 0 {
		e.getEmit(t)
		if len(t.PK) == 1 {
			e.getManyEmit(t)
		}
	}
	for _, f := range t.UniqueFields() {
		e.getByEmit(t, f)
	}
	e.listEmit(t)
	e.createEmit(t)
	e.createManyEmit(t)
	if len(t.PK) > 0 {
		if len(t.NonPK()) > 0 {
			e.updateEmit(t)
		}
		e.deleteEmit(t)
	}
}

func identityParams(t *naming.Table) string {
	parts := make([]string, len(t.PK))
	for i, f := range t.PK {
		parts[i] = f.Arg + " " + f.GoType
	}
	return strings.Join(parts, ", ")
}

func argsList(args []string) string {
	if len(args) == 0 {
		return "nil"
	}
	return "[]any{" + strings.Join(args, ", ") + "}"
}

func (e *queryEmitter) getEmit(t *naming.Table) {
	b := &e.body
	sql, args, err := t.GetSQL()
	if err != nil {
		e.fail(t, "Get", err)
		return
	}
	fmt.Fprintf(b, "const %s = `%s`\n\n", t.Names.GetConst, sql)
	fmt.Fprintf(b, "func %s(%s) rt.Lookup[%s] {\n", t.Names.Get, identityParams(t), t.Model)
	fmt.Fprintf(b, "\treturn rt.Lookup[%s]{SQL: %s, Args: %s, Scan: %s}\n}\n\n", t.Model, t.Names.GetConst, argsList(args), t.Names.Scan)
}

func (e *queryEmitter) getManyEmit(t *naming.Table) {
	b := &e.body
	key := t.PK[0]
	fmt.Fprintf(b, "func %s(%ss []%s) rt.Query[%s] {\n", t.Names.GetMany, key.Arg, key.GoType, t.Model)
	fmt.Fprintf(b, "\tif len(%ss) == 0 {\n\t\treturn rt.Query[%s]{}\n\t}\n", key.Arg, t.Model)
	fmt.Fprintf(b, "\tvoltSQL, voltArgs, voltErr := rt.SelectRender(%s, %s, []rt.Opt[%s]{%s.In(%ss...)})\n", t.Names.TableConst, t.Names.ColumnsConst, t.Model, t.Handle(key), key.Arg)
	queryReturn(b, t.Model, t.Names.Scan)
}

func queryReturn(b *strings.Builder, model, scan string) {
	fmt.Fprintf(b, "\treturn rt.Query[%s]{SQL: voltSQL, Args: voltArgs, Scan: %s, Err: voltErr}\n}\n\n", model, scan)
}

func (e *queryEmitter) getByEmit(t *naming.Table, f *naming.Field) {
	b := &e.body
	sql, args, err := t.GetBySQL(f)
	if err != nil {
		e.fail(t, "GetBy"+f.GoField, err)
		return
	}
	fmt.Fprintf(b, "const %s = `%s`\n\n", t.GetByConst(f), sql)
	fmt.Fprintf(b, "func %s(%s %s) rt.Lookup[%s] {\n", t.GetBy(f), f.Arg, f.GoType, t.Model)
	fmt.Fprintf(b, "\treturn rt.Lookup[%s]{SQL: %s, Args: %s, Scan: %s}\n}\n\n", t.Model, t.GetByConst(f), argsList(args), t.Names.Scan)
}

func (e *queryEmitter) listEmit(t *naming.Table) {
	b := &e.body
	sql, _, err := t.ListSQL()
	if err != nil {
		e.fail(t, "List", err)
		return
	}
	fmt.Fprintf(b, "const %s = `%s`\n\n", t.Names.ListConst, sql)
	funcLine(b, fmt.Sprintf("func %s() rt.Query[%s]", t.Names.List, t.Model),
		fmt.Sprintf("return rt.Query[%s]{SQL: %s, Scan: %s}", t.Model, t.Names.ListConst, t.Names.Scan))
}

func (e *queryEmitter) createEmit(t *naming.Table) {
	funcLine(&e.body, fmt.Sprintf("func %s(c %s) rt.Write[%s]", t.Names.Create, t.Names.Changeset, t.Model),
		"return rt.Insert(c.Validate().Changeset)")
}

func (e *queryEmitter) createManyEmit(t *naming.Table) {
	b := &e.body
	fmt.Fprintf(b, "func %s(cs []%s) rt.Batch {\n", t.Names.CreateMany, t.Names.Changeset)
	fmt.Fprintf(b, "\tvoltCs := make([]rt.Changeset[%s], len(cs))\n", t.Model)
	b.WriteString("\tfor voltI, voltC := range cs {\n\t\tvoltCs[voltI] = voltC.Validate().Changeset\n\t}\n")
	b.WriteString("\treturn rt.InsertMany(voltCs)\n}\n\n")
}

func (e *queryEmitter) updateEmit(t *naming.Table) {
	funcLine(&e.body, fmt.Sprintf("func %s(c %s) rt.Write[%s]", t.Names.Update, t.Names.Changeset, t.Model),
		"return rt.Update(c.Validate().Changeset)")
}

func (e *queryEmitter) deleteEmit(t *naming.Table) {
	b := &e.body
	sql, args, err := t.DeleteSQL()
	if err != nil {
		e.fail(t, "Delete", err)
		return
	}
	fmt.Fprintf(b, "const %s = `%s`\n\n", t.Names.DeleteConst, sql)
	fmt.Fprintf(b, "func %s(%s) rt.Exec {\n", t.Names.Delete, identityParams(t))
	fmt.Fprintf(b, "\treturn rt.Exec{SQL: %s, Args: %s, Model: %q, One: true}\n}\n\n", t.Names.DeleteConst, argsList(args), t.Model)
}
