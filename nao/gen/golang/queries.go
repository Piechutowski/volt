// CRUD generation (volt_queries.go): the static query surface as values,
// one function per statement returning the rt effect the runner
// performs (spec/generated-query-surface, spec/predicates).
package golang

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/naming"
)

// GenerateQueries renders the queries file for one checked schema file.
func GenerateQueries(f *ast.File, info *check.Info, opts Options) ([]byte, error) {
	return Queries(naming.PlanBuild(f, info), opts)
}

// Queries renders the queries file (volt_queries.go) for the planned
// package (spec/generated-query-surface).
func Queries(pl *naming.Plan, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if err := pl.Err(); err != nil {
		return nil, err
	}
	e := &queryEmitter{tables: pl.Tables(), opts: opts}
	e.run()
	if e.err != nil {
		return nil, e.err
	}
	return align.Finish(e.out.String()), nil
}

func scanTarget(f *naming.Field) string {
	switch {
	case f.PlainBytes():
		return "(*rt.Bytes)(&voltV." + f.GoField + ")"
	case f.Kinded && !f.Nullable:
		return "(*" + f.Storage + ")(&voltV." + f.GoField + ")"
	case f.GoType == "time.Time":
		return "(*rt.Time)(&voltV." + f.GoField + ")"
	}
	return "&voltV." + f.GoField
}

type queryEmitter struct {
	tables []*naming.Table
	opts   Options
	out    strings.Builder
	body   strings.Builder
	err    error

	needImports map[string]bool
}

func (e *queryEmitter) fail(t *naming.Table, what string, err error) {
	if e.err == nil {
		e.err = fmt.Errorf("table %s: %s: %w", t.Info.Decl.Name.Name(), what, err)
	}
}

func (e *queryEmitter) run() {
	e.needImports = map[string]bool{}
	e.body.Grow(fieldCount(e.tables)*100 + len(e.tables)*1200)
	for _, t := range e.tables {
		e.tableEmit(t)
	}
	e.header()
	e.out.Grow(e.body.Len())
	e.out.WriteString(e.body.String())
}

func (e *queryEmitter) header() {
	fmt.Fprintf(&e.out, "// Code generated by volt gen from %s. DO NOT EDIT.\n", e.opts.Source)
	e.out.WriteString("\n")
	fmt.Fprintf(&e.out, "package %s\n\n", e.opts.Package)

	imports := map[string]bool{rtImport: true}
	for imp := range e.needImports {
		imports[imp] = true
	}
	e.out.WriteString("import (\n")
	for _, p := range importKeysSort(imports) {
		fmt.Fprintf(&e.out, "\t%s\n", importDecl(p))
	}
	e.out.WriteString(")\n\n")
}

func (e *queryEmitter) tableEmit(t *naming.Table) {
	if len(t.Fields) == 0 {
		return
	}
	if len(t.PK) > 0 {
		for _, f := range t.PK {
			e.needImports[f.Imp] = true
		}
	}
	for _, f := range t.UniqueFields() {
		e.needImports[f.Imp] = true
	}
	delete(e.needImports, "")

	if len(t.PK) > 0 {
		e.getEmit(t)
		if len(t.PK) == 1 {
			e.getManyEmit(t)
		}
	}
	for _, f := range t.UniqueFields() {
		e.getByEmit(t, f)
	}
	e.listEmit(t)
	e.createEmit(t)
	e.createManyEmit(t)
	if len(t.PK) > 0 {
		if len(t.NonPK()) > 0 {
			e.updateEmit(t)
		}
		e.deleteEmit(t)
	}
}

func identityParams(t *naming.Table) []string {
	parts := make([]string, len(t.PK))
	for i, f := range t.PK {
		parts[i] = f.Arg + " " + f.GoType
	}
	return parts
}

func statement(effect, sqlName string, args []string, scan string, extra ...string) elem {
	return stmt("return ", statementLiteral(effect, sqlName, args, scan, extra...))
}

func statementLiteral(effect, sqlName string, args []string, scan string, extra ...string) elem {
	keys := []string{"SQL"}
	vals := elems{text(sqlName)}
	if len(args) > 0 {
		keys, vals = append(keys, "Args"), append(vals, values("[]any", texts(args...)...))
	}
	if scan != "" {
		keys, vals = append(keys, "Scan"), append(vals, text(scan))
	}
	for i := 1; i < len(extra); i += 2 {
		keys, vals = append(keys, extra[i-1]), append(vals, text(extra[i]))
	}
	return literal(effect, keys, vals...)
}

func (e *queryEmitter) getEmit(t *naming.Table) {
	b := &e.body
	sql, args, err := t.GetSQL()
	if err != nil {
		e.fail(t, "Get", err)
		return
	}
	sqlConst(b, t.Names.GetConst, sql)
	effect := "rt.Lookup[" + t.Model + "]"
	funcEmit(b, "func "+t.Names.Get, identityParams(t), effect, statement(effect, t.Names.GetConst, args, t.Names.Scan))
}

func (e *queryEmitter) getManyEmit(t *naming.Table) {
	b := &e.body
	key := t.PK[0]
	keys := key.Arg + "s"
	effect := "rt.Query[" + t.Model + "]"
	funcEmit(b, "func "+t.Names.GetMany, []string{keys + " []" + key.GoType}, effect,
		text("if len("+keys+") == 0 {\n\t\treturn rt.Empty["+t.Model+"]()\n\t}"),
		stmt("voltSQL, voltArgs, voltErr := ", call("rt.SelectRender",
			text(t.Names.TableConst), text(t.Names.ColumnsConst), calls(t.Handle(key)+".In", keys+"..."))),
		renderedReturn(effect, t.Names.Scan))
}

func (e *queryEmitter) getByEmit(t *naming.Table, f *naming.Field) {
	b := &e.body
	sql, args, err := t.GetBySQL(f)
	if err != nil {
		e.fail(t, "GetBy"+f.GoField, err)
		return
	}
	sqlConst(b, t.GetByConst(f), sql)
	effect := "rt.Lookup[" + t.Model + "]"
	funcEmit(b, "func "+t.GetBy(f), []string{f.Arg + " " + f.GoType}, effect, statement(effect, t.GetByConst(f), args, t.Names.Scan))
}

func (e *queryEmitter) listEmit(t *naming.Table) {
	b := &e.body
	sql, _, err := t.ListSQL()
	if err != nil {
		e.fail(t, "List", err)
		return
	}
	sqlConst(b, t.Names.ListConst, sql)
	effect := "rt.Query[" + t.Model + "]"
	funcEmit(b, "func "+t.Names.List, nil, effect, statement(effect, t.Names.ListConst, nil, t.Names.Scan))
}

func (e *queryEmitter) createEmit(t *naming.Table) {
	funcEmit(&e.body, "func "+t.Names.Create, []string{"c " + t.Names.Changeset}, "rt.Write["+t.Model+"]",
		stmt("return ", call("rt.Insert", text("c.Validate().Changeset"))))
}

func (e *queryEmitter) createManyEmit(t *naming.Table) {
	b := &e.body
	funcEmit(b, "func "+t.Names.CreateMany, []string{"cs []" + t.Names.Changeset}, "rt.Batch",
		stmt("voltCs := ", calls("make", "[]rt.Changeset["+t.Model+"]", "len(cs)")),
		text("for voltI, voltC := range cs {\n\t\tvoltCs[voltI] = voltC.Validate().Changeset\n\t}"),
		text("return rt.InsertMany(voltCs)"))
}

func (e *queryEmitter) updateEmit(t *naming.Table) {
	funcEmit(&e.body, "func "+t.Names.Update, []string{"c " + t.Names.Changeset}, "rt.Write["+t.Model+"]",
		stmt("return ", call("rt.Update", text("c.Validate().Changeset"))))
}

func (e *queryEmitter) deleteEmit(t *naming.Table) {
	b := &e.body
	sql, args, err := t.DeleteSQL()
	if err != nil {
		e.fail(t, "Delete", err)
		return
	}
	sqlConst(b, t.Names.DeleteConst, sql)
	funcEmit(b, "func "+t.Names.Delete, identityParams(t), "rt.Exec",
		statement("rt.Exec", t.Names.DeleteConst, args, "", "Model", strconv.Quote(t.Model), "One", "true"))
}
