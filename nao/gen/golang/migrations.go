// The volt_migrations.go emitter (spec §migration-tooling): the
// package's migrations in their statement form and Migrate, so that a
// binary migrates its own database without the volt tool.
package golang

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/migrate"
	"github.com/Piechutowski/volt/nao/rt"
)

// GenerateMigrations renders volt_migrations.go for a package that
// declares migrations (spec §migration-tooling): Migrations,
// every migration in name order with its statements in both directions
// and its flags, and Migrate over rt.MigrateUp. It imports context,
// database/sql and rt only.
func GenerateMigrations(f *ast.File, info *check.Info, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	ms, err := migrate.Lower(info)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by volt gen from %s. DO NOT EDIT.\n\n", opts.Source)
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	fmt.Fprintf(&b, "import (\n\t\"context\"\n\t\"database/sql\"\n\n\t%q\n)\n\n", rtImport)
	b.WriteString("// Migrations is every migration of the package in name order, in the\n")
	b.WriteString("// statement form the runtime applies (spec §migration-tooling).\n")
	b.WriteString("var Migrations = []rt.Migration{\n")
	for _, m := range ms {
		b.WriteString("\t{\n")
		migrationFieldsEmit(&b, m)
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// Migrate applies every pending migration of Migrations to db (spec\n")
	b.WriteString("// §migration-tooling). Nothing calls it unless the application does.\n")
	b.WriteString("func Migrate(ctx context.Context, db *sql.DB) error {\n")
	b.WriteString("\t_, err := rt.MigrateUp(ctx, db, Migrations)\n\treturn err\n}\n")
	return []byte(b.String()), nil
}

type migrationField struct {
	key, value string
	multiline  bool
}

// migrationFieldsEmit writes one rt.Migration literal's fields as gofmt
// lays them out: consecutive one-line fields share a key column, and a
// multi-line field stands alone.
func migrationFieldsEmit(b *strings.Builder, m rt.Migration) {
	fields := []migrationField{{key: "Name", value: strconv.Quote(m.Name)}}
	fields = append(fields, statementsField("Up", m.Up))
	if m.Down != nil {
		fields = append(fields, statementsField("Down", m.Down))
	}
	if m.NoTransaction {
		fields = append(fields, migrationField{key: "NoTransaction", value: "true"})
	}
	if m.ForeignKeysOff {
		fields = append(fields, migrationField{key: "ForeignKeysOff", value: "true"})
	}
	for i := 0; i < len(fields); {
		if fields[i].multiline {
			fmt.Fprintf(b, "\t\t%s: %s,\n", fields[i].key, fields[i].value)
			i++
			continue
		}
		j, width := i, 0
		for ; j < len(fields) && !fields[j].multiline; j++ {
			if len(fields[j].key) > width {
				width = len(fields[j].key)
			}
		}
		for ; i < j; i++ {
			fmt.Fprintf(b, "\t\t%s:%s %s,\n", fields[i].key, strings.Repeat(" ", width-len(fields[i].key)), fields[i].value)
		}
	}
}

func statementsField(key string, stmts []string) migrationField {
	if len(stmts) == 0 {
		return migrationField{key: key, value: "[]string{}"}
	}
	var b strings.Builder
	b.WriteString("[]string{\n")
	for _, s := range stmts {
		b.WriteString("\t\t\t" + goStringLit(s) + ",\n")
	}
	b.WriteString("\t\t}")
	return migrationField{key: key, value: b.String(), multiline: true}
}

// goStringLit renders a statement as a raw string, or as a quoted
// string when it holds a backquote.
func goStringLit(s string) string {
	if strings.ContainsRune(s, '`') {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}
