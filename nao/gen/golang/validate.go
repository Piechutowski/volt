// Validator generation (docs/spec.md §V12): one Validate method per
// table that carries typed or Go-reference checks. Typed conditions
// arrive pre-rendered by the checker — the same walk that rendered the
// SQL CHECK, so the two tiers cannot disagree; Go-reference calls name
// hand-written functions of the containing package, which the Go
// compiler proves exist (the §V4.3 pattern).
package golang

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
)

// GenerateValidators renders nao_validate.go for the given tables.
// fns must be non-empty; the caller decides whether the file exists.
func GenerateValidators(f *ast.File, info *check.Info, fns []CheckFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	p, err := planBuild(f, info)
	if err != nil {
		return nil, err
	}
	byKey := map[string]*tableModel{}
	for _, t := range p.tables {
		byKey[t.ti.Key] = t
	}

	var body strings.Builder
	usesRt := false
	for _, fn := range fns {
		t := byKey[fn.TableKey]
		if t == nil {
			return nil, fmt.Errorf("validator: no table %q in the plan", fn.TableKey)
		}
		usesRt = true
		fmt.Fprintf(&body, "// Validate evaluates every check of %s against the row's values\n// (spec §V12). Typed checks are also CHECK constraints in the DDL;\n// Go-reference checks run here only — SQLite cannot call Go.\n", t.sqlName)
		validateEmit(&body, t.model, t.model, fn.Checks)

		// Params structs validate the checks they can see (§V12.6): a
		// generated Create/Update handler calls these before the query.
		create, update := paramsChecks(t, fn.Checks)
		if len(create) > 0 {
			fmt.Fprintf(&body, "// Validate evaluates the checks of %s whose columns %sCreateParams carries\n// (spec §V12.6)%s.\n", t.sqlName, t.model, skippedNote(fn.Checks, create))
			validateEmit(&body, t.model+"CreateParams", t.model, create)
		}
		if len(update) > 0 {
			fmt.Fprintf(&body, "// Validate evaluates the checks of %s whose columns %sUpdateParams carries\n// (spec §V12.6)%s.\n", t.sqlName, t.model, skippedNote(fn.Checks, update))
			validateEmit(&body, t.model+"UpdateParams", t.model, update)
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by nao gen from %s; DO NOT EDIT.\n", opts.Source)
	out.WriteString("//\n// Validators for the schema's checks (docs/spec.md §V12): typed\n// checks evaluate exactly like their SQL CHECK twins; Go-reference\n// checks call hand-written functions of this package.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", opts.Package)
	var imports []string
	if usesRt {
		imports = append(imports, rtImport)
	}
	sort.Strings(imports)
	out.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.WriteString(body.String())

	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("generated validators do not parse: %w\n%s", err, out.String())
	}
	return src, nil
}

// validateEmit renders one Validate method on recv over checks, each
// failure an rt.CheckError naming model, joined as an rt.ValidationError.
func validateEmit(body *strings.Builder, recv, model string, checks []CheckSpec) {
	fmt.Fprintf(body, "func (v %s) Validate() error {\n\tvar errs []rt.CheckError\n", recv)
	for _, ck := range checks {
		name := ck.Name
		if name == "" {
			name = ck.Src
		}
		cols := "nil"
		if len(ck.Cols) > 0 {
			cols = fmt.Sprintf("%#v", ck.Cols)
		}
		switch {
		case ck.Cond != "":
			fmt.Fprintf(body, "\tif !(%s) {\n\t\terrs = append(errs, rt.CheckError{Model: %q, Check: %q, Columns: %s})\n\t}\n",
				ck.Cond, model, name, cols)
		case ck.Call != "":
			fmt.Fprintf(body, "\tif err := %s; err != nil {\n\t\terrs = append(errs, rt.CheckError{Model: %q, Check: %q, Columns: %s, Cause: err})\n\t}\n",
				ck.Call, model, name, cols)
		}
	}
	body.WriteString("\treturn rt.Validation(errs)\n}\n\n")
}

// skippedNote names the checks a params struct cannot evaluate.
func skippedNote(all, kept []CheckSpec) string {
	var skipped []string
	for _, ck := range all {
		found := false
		for _, k := range kept {
			if k.Src == ck.Src {
				found = true
			}
		}
		if !found {
			name := ck.Name
			if name == "" {
				name = ck.Src
			}
			skipped = append(skipped, name)
		}
	}
	if len(skipped) == 0 {
		return ""
	}
	return "; left to the row and the DDL: " + strings.Join(skipped, ", ")
}
