// Validate generation (spec/changesets, spec/validators): one Validate
// method per table on its changeset, running required and the validators
// of the containing package over the row.
package golang

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/gen/layout"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/naming"
)

// GenerateValidators renders volt_validate.go for one checked schema file;
// fns carries the validators the Volt checker lowered, none for a plain
// schema.
func GenerateValidators(f *ast.File, info *check.Info, fns []naming.ValidatorFn, opts Options) ([]byte, error) {
	return Validators(naming.PlanBuild(f, info), fns, opts)
}

// Validators renders volt_validate.go for the planned package
// (spec/validators).
func Validators(pl *naming.Plan, fns []naming.ValidatorFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if err := pl.Err(); err != nil {
		return nil, err
	}
	specs := make(map[string][]naming.ValidatorSpec, len(fns))
	for _, fn := range fns {
		if _, err := pl.Table(fn.TableKey); err != nil {
			return nil, fmt.Errorf("validator: no table %q in the plan", fn.TableKey)
		}
		specs[fn.TableKey] = fn.Validators
	}

	var body strings.Builder
	usesRt := false
	for _, t := range pl.Tables() {
		if len(t.Fields) == 0 {
			continue
		}
		usesRt = validateEmit(&body, t, specs[t.Info.Key]) || usesRt
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by volt gen from %s. DO NOT EDIT.\n", opts.Source)
	out.WriteString("\n")
	fmt.Fprintf(&out, "package %s\n", opts.Package)
	if usesRt {
		fmt.Fprintf(&out, "\nimport (\n\t%s\n)\n", importDecl(rtImport))
	}
	if body.Len() > 0 {
		out.WriteString("\n")
		out.WriteString(body.String())
	}
	return align.Finish(out.String()), nil
}

func validateEmit(b *strings.Builder, t *naming.Table, specs []naming.ValidatorSpec) bool {
	var checks strings.Builder
	for _, f := range t.Fields {
		if f.Required {
			requiredEmit(&checks, f)
		}
	}
	for _, ck := range specs {
		args := make([]string, len(ck.Fields))
		for i, f := range ck.Fields {
			args[i] = "voltV." + f
		}
		layout.WriteLine(&checks, 1, "if voltErr := ", calls(ck.Name, args...), "; voltErr != nil {\n")
		findingEmit(&checks, strconv.Quote(ck.Name), ck.Cols, "voltErr.Error()")
	}

	sig := layout.Signature("func (c "+t.Names.Changeset+") Validate", nil, []string{t.Names.Changeset}, " {")
	layout.WriteLine(b, 0, "", sig, "\n")
	if checks.Len() == 0 {
		layout.WriteLine(b, 1, "return ", values(t.Names.Changeset, calls("c.WithFindings")), "\n}\n\n")
		return false
	}
	b.WriteString("\tvoltV := c.Row()\n\tvar voltErrs []rt.FieldError\n")
	b.WriteString(checks.String())
	layout.WriteLine(b, 1, "return ", values(t.Names.Changeset, calls("c.WithFindings", "voltErrs...")), "\n}\n\n")
	return true
}

func findingEmit(b *strings.Builder, check string, cols []string, message string) {
	quoted := make([]string, len(cols))
	for i, c := range cols {
		quoted[i] = strconv.Quote(c)
	}
	finding := literal("rt.FieldError", []string{"Check", "Columns", "Message"},
		text(check), values("[]string", texts(quoted...)...), text(message))
	layout.WriteLine(b, 2, "voltErrs = ", call("append", text("voltErrs"), finding), "\n")
	b.WriteString("\t}\n")
}

func requiredEmit(b *strings.Builder, f *naming.Field) {
	var cond string
	switch {
	case f.Declared && !f.Kinded:
		cond = "rt.Blank(voltV." + f.GoField + ")"
	case f.Storage == "string":
		cond = "voltV." + f.GoField + ` == ""`
	case f.Storage == "[]byte":
		cond = "len(voltV." + f.GoField + ") == 0"
	default:
		cond = "voltV." + f.GoField + " == 0"
	}
	b.WriteString("\tif " + cond + " {\n")
	findingEmit(b, "\"required\"", []string{f.ColName}, strconv.Quote(f.ColName+" is required"))
}
