// Validate generation (docs/spec.md §changesets, §validators): one Validate
// method per table on its changeset, running required, enum membership and
// the validators of the containing package over the row.
package golang

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
)

// GenerateValidators renders nao_validate.go for one checked DBML file;
// fns carries the validators the Volt checker lowered, none for a plain
// schema.
func GenerateValidators(f *ast.File, info *check.Info, fns []ValidatorFn, opts Options) ([]byte, error) {
	return PlanBuild(f, info).Validators(fns, opts)
}

// Validators renders nao_validate.go for the planned package.
func (pl *Plan) Validators(fns []ValidatorFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if pl.err != nil {
		return nil, pl.err
	}
	specs := make(map[string][]ValidatorSpec, len(fns))
	for _, fn := range fns {
		if pl.byKey[fn.TableKey] == nil {
			return nil, fmt.Errorf("validator: no table %q in the plan", fn.TableKey)
		}
		specs[fn.TableKey] = fn.Validators
	}

	var body strings.Builder
	usesRt := false
	for _, t := range pl.p.tables {
		if len(t.fields) == 0 {
			continue
		}
		usesRt = validateEmit(&body, t, specs[t.ti.Key]) || usesRt
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by nao gen from %s; DO NOT EDIT.\n", opts.Source)
	out.WriteString("\n")
	fmt.Fprintf(&out, "package %s\n", opts.Package)
	if usesRt {
		fmt.Fprintf(&out, "\nimport (\n\t%s\n)\n", importDecl(rtImport))
	}
	if body.Len() > 0 {
		out.WriteString("\n")
		out.WriteString(body.String())
	}
	return align.Finish(out.String()), nil
}

func validateEmit(b *strings.Builder, t *tableModel, specs []ValidatorSpec) bool {
	m := t.model
	tbl := t.ti.Decl.Name.String()
	var checks strings.Builder
	for _, f := range t.fields {
		if f.required {
			requiredEmit(&checks, f)
		}
	}
	for _, f := range t.fields {
		if f.enum != nil {
			enumEmit(&checks, t, f)
		}
	}
	for _, ck := range specs {
		fmt.Fprintf(&checks, "\tif err := %s; err != nil {\n", ck.Call)
		fmt.Fprintf(&checks, "\t\terrs = append(errs, rt.FieldError{Check: %q, Columns: %#v, Message: err.Error()})\n\t}\n", ck.Name, ck.Cols)
	}

	fmt.Fprintf(b, "// Validate runs required, enum membership and the validators of %s\n", tbl)
	fmt.Fprintf(b, "// over the row, every one every time, replacing the findings of an\n")
	fmt.Fprintf(b, "// earlier Validate (spec §changesets, §validators).\n")
	fmt.Fprintf(b, "func (c %sChangeset) Validate() %sChangeset {\n", m, m)
	if checks.Len() == 0 {
		b.WriteString("\tc.valid = nil\n\treturn c\n}\n\n")
		return false
	}
	b.WriteString("\tv := c.Row()\n\tvar errs []rt.FieldError\n")
	b.WriteString(checks.String())
	b.WriteString("\tc.valid = errs\n\treturn c\n}\n\n")
	return true
}

func requiredEmit(b *strings.Builder, f *fieldPlan) {
	var cond string
	switch {
	case f.declared:
		cond = "rt.Blank(v." + f.goField + ")"
	case f.enum != nil, f.storage == "string":
		cond = "v." + f.goField + ` == ""`
	case f.storage == "[]byte":
		cond = "len(v." + f.goField + ") == 0"
	default:
		cond = "v." + f.goField + " == 0"
	}
	fmt.Fprintf(b, "\tif %s {\n", cond)
	fmt.Fprintf(b, "\t\terrs = append(errs, rt.FieldError{Check: \"required\", Columns: []string{%q}, Message: %q})\n\t}\n", f.colName, f.colName+" is required")
}

func enumEmit(b *strings.Builder, t *tableModel, f *fieldPlan) {
	var consts []string
	for _, v := range f.enum.Decl.Values {
		name, err := goName(v.Name.Name())
		if err != nil {
			continue
		}
		consts = append(consts, f.baseType+name)
	}
	value := "v." + f.goField
	guard := fmt.Sprintf("c.set[%d] || c.row", t.index(f))
	if f.nullable {
		value += ".V"
		guard = "(" + guard + ") && v." + f.goField + ".Valid"
	}
	msg := f.colName + " is not a value of " + f.enum.Decl.Name.String()
	fmt.Fprintf(b, "\tif %s {\n\t\tswitch %s {\n\t\tcase %s:\n\t\tdefault:\n", guard, value, strings.Join(consts, ", "))
	fmt.Fprintf(b, "\t\t\terrs = append(errs, rt.FieldError{Check: \"enum\", Columns: []string{%q}, Message: %s})\n\t\t}\n\t}\n", f.colName, strconv.Quote(msg))
}
