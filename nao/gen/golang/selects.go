// Select generation (spec/selects-over-groups): one typed method per
// (select × group member), its statement rendered by the runtime from the
// predicate tree the checker lowered (spec/predicates), plus the
// projection row types.
package golang

import (
	"fmt"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/naming"
)

// GenerateSelects renders volt_selects.go for the given instantiations.
// fns must be non-empty.
func GenerateSelects(f *ast.File, info *check.Info, fns []naming.SelectFn, opts Options) ([]byte, error) {
	return Selects(naming.PlanBuild(f, info), fns, opts)
}

// Selects renders volt_selects.go for the planned package
// (spec/selects-over-groups).
func Selects(pl *naming.Plan, fns []naming.SelectFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if err := pl.Err(); err != nil {
		return nil, err
	}

	var body strings.Builder
	imports := map[string]bool{rtImport: true}
	sharedDone := map[string]bool{}
	for _, fn := range fns {
		t, err := pl.Table(fn.TableKey)
		if err != nil {
			return nil, fmt.Errorf("select %s: no table %q in the plan", fn.MethodSuffix, fn.TableKey)
		}
		for _, prm := range fn.Params {
			if imp := typeImport(t, strings.TrimPrefix(prm.GoType, "[]")); imp != "" {
				imports[imp] = true
			}
		}
		cols, err := pl.SelectColumns(fn)
		if err != nil {
			return nil, err
		}
		switch {
		case fn.SharedType != "":
			if !sharedDone[fn.SharedType] {
				sharedDone[fn.SharedType] = true
				fmt.Fprintf(&body, "type %s struct {\n", fn.SharedType)
				var rows align.Block
				for _, f := range cols {
					fieldImports(imports, f)
					rows.Row(f.GoField, f.GoType, fmt.Sprintf("`db:%q json:%q`", f.WireName(), f.WireName()))
				}
				rows.WriteTo(&body, "\t")
				body.WriteString("}\n\n")
				rowScanEmit(&body, fn.SharedType, cols)
				imports[rtImport] = true
			}
		case len(fn.Excluded) > 0:
			row, err := pl.SelectRowName(fn)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&body, "type %s struct {\n", row)
			var rows align.Block
			for _, f := range cols {
				fieldImports(imports, f)
				if doc := f.Col.Doc.Text(); doc != "" {
					commentLines(&rows, doc)
				}
				rows.Row(f.GoField, f.GoType, "`"+f.Tag+"`")
			}
			rows.WriteTo(&body, "\t")
			body.WriteString("}\n\n")
			rowScanEmit(&body, row, cols)
			imports[rtImport] = true
		}
		if err := selectEmit(&body, imports, pl, t, fn); err != nil {
			return nil, err
		}
		if fn.With != nil {
			if err := withEmit(&body, pl, t, fn, sharedDone); err != nil {
				return nil, err
			}
		}
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by volt gen from %s. DO NOT EDIT.\n", opts.Source)
	out.WriteString("\n")
	fmt.Fprintf(&out, "package %s\n\n", opts.Package)
	out.WriteString("import (\n")
	for _, imp := range importKeysSort(imports) {
		fmt.Fprintf(&out, "\t%s\n", importDecl(imp))
	}
	out.WriteString(")\n\n")
	out.WriteString(body.String())

	return align.Finish(out.String()), nil
}

func fieldImports(imports map[string]bool, f *naming.Field) {
	if f.Imp != "" {
		imports[f.Imp] = true
	}
	if f.GoType != f.BaseType {
		imports[rtImport] = true
	}
}

func typeImport(t *naming.Table, goType string) string {
	for _, f := range t.Fields {
		if f.BaseType == goType {
			return f.Imp
		}
	}
	return ""
}

func rowScanEmit(b *strings.Builder, row string, cols []*naming.Field) {
	targets := make(elems, len(cols))
	for i, f := range cols {
		targets[i] = text(scanTarget(f))
	}
	funcEmit(b, "func "+naming.RowScan(row), []string{"r rt.Row"}, "("+row+", error)",
		text("var voltV "+row),
		stmt("voltErr := ", call("r.Scan", targets...)),
		text("return voltV, voltErr"))
}

func selectEmit(b *strings.Builder, imports map[string]bool, pl *naming.Plan, t *naming.Table, fn naming.SelectFn) error {
	row, err := pl.SelectRowName(fn)
	if err != nil {
		return err
	}
	name := t.SelectMethod(fn)
	constName := t.SelectConst(fn)

	sql, args, err := pl.SelectSQL(fn)
	if err != nil {
		return fmt.Errorf("select %s: %w", name, err)
	}
	sqlConst(b, constName, sql)

	params := make([]string, len(fn.Params))
	for i, prm := range fn.Params {
		params[i] = prm.GoName + " " + prm.Type()
	}
	for _, a := range args {
		if strings.HasPrefix(a, "rt.") {
			imports[rtImport] = true
		}
	}
	effect := "rt.Query"
	if fn.Lookup {
		effect = "rt.Lookup"
	}
	var check []string
	if fn.LimitParam != "" {
		check = []string{"Err", "rt.LimitCheck(" + fn.LimitParam + ")"}
	}
	if fn.With != nil {
		return withSelectEmit(b, pl, t, fn, row, params, statementLiteral("rt.Query["+row+"]", constName, args, naming.RowScan(row), check...))
	}
	if fn.Doc != "" {
		commentWrite(b, fn.Doc)
	}
	kind := effect + "[" + row + "]"
	funcEmit(b, "func "+name, params, kind, statement(kind, constName, args, naming.RowScan(row), check...))
	return nil
}

func withSelectEmit(b *strings.Builder, pl *naming.Plan, t *naming.Table, fn naming.SelectFn, row string, params []string, parent elem) error {
	w := fn.With
	child, err := pl.Table(w.TableKey)
	if err != nil {
		return err
	}
	key := t.Field(w.ParentKey)
	childKey := child.Field(w.ChildKey)
	if key == nil || childKey == nil {
		return fmt.Errorf("select %s: the key columns of with are not in the plan", t.SelectMethod(fn))
	}
	childValue := "voltC." + childKey.GoField
	if childKey.Nullable {
		childValue += ".V"
	}
	kind := fmt.Sprintf("rt.With[%s, %s, %s, %s]", row, child.Model, key.BaseType, w.RowType)
	built := literal(w.RowType, []string{row, w.Field}, texts("voltP", "voltCs")...)
	build := funcLit([]string{"voltP " + row, "voltCs []" + child.Model}, w.RowType, stmt("return ", built))
	keys := []string{"Parent", "Child", "ChildScan", "ParentKey", "ChildKey", "Build"}
	vals := elems{
		parent,
		text(withConst(t, fn)),
		text(child.Names.Scan),
		funcLit([]string{"voltP " + row}, key.BaseType, text("return voltP."+key.GoField)),
		funcLit([]string{"voltC " + child.Model}, key.BaseType, text("return "+childValue)),
		build,
	}
	if fn.Doc != "" {
		commentWrite(b, fn.Doc)
	}
	funcEmit(b, "func "+t.SelectMethod(fn), params, kind, stmt("return ", literal(kind, keys, vals...)))
	return nil
}

// withEmit writes the row type of a nested select and the statement that
// loads its children (spec/selects-over-groups).
func withEmit(b *strings.Builder, pl *naming.Plan, t *naming.Table, fn naming.SelectFn, done map[string]bool) error {
	w := fn.With
	child, err := pl.Table(w.TableKey)
	if err != nil {
		return err
	}
	row, err := pl.SelectRowName(fn)
	if err != nil {
		return err
	}
	if !done[w.RowType] {
		done[w.RowType] = true
		fmt.Fprintf(b, "type %s struct {\n\t%s\n\t%s []%s `json:%q`\n}\n\n", w.RowType, row, w.Field, child.Model, w.Name)
	}
	sql, err := pl.WithChildSQL(fn)
	if err != nil {
		return err
	}
	sqlConst(b, withConst(t, fn), sql)
	return nil
}

func withConst(t *naming.Table, fn naming.SelectFn) string {
	return "volt" + t.Model + fn.MethodSuffix + "ChildrenSQL"
}
