// Select generation (docs/spec.md §selects-over-groups rule 6-§selects-over-groups rule 7): one typed method per
// (select × group member), over WHERE/ORDER fragments the checker has
// already typed and rendered, plus the projection row types.
package golang

import (
	"fmt"
	"sort"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
)

// GenerateSelects renders nao_selects.go for the given instantiations.
// fns must be non-empty.
func GenerateSelects(f *ast.File, info *check.Info, fns []SelectFn, opts Options) ([]byte, error) {
	return PlanBuild(f, info).Selects(fns, opts)
}

// Selects renders nao_selects.go for the planned package.
func (pl *Plan) Selects(fns []SelectFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if pl.err != nil {
		return nil, pl.err
	}
	byKey := pl.byKey

	var body strings.Builder
	imports := map[string]bool{"context": true}
	sharedDone := map[string]bool{}
	for _, fn := range fns {
		t := byKey[fn.TableKey]
		if t == nil {
			return nil, fmt.Errorf("select %s: no table %q in the plan", fn.MethodSuffix, fn.TableKey)
		}
		if len(fn.Params) > 0 {
			imports["database/sql"] = true
		}
		for _, prm := range fn.Params {
			if strings.HasPrefix(prm.GoType, "time.") {
				imports["time"] = true
			}
			if strings.HasPrefix(prm.GoType, "[]") {
				imports[rtImport] = true // rt.JSONList binds a list parameter
			}
		}
		cols, err := selectColumns(t, fn)
		if err != nil {
			return nil, err
		}
		switch {
		case fn.SharedType != "":
			if !sharedDone[fn.SharedType] {
				sharedDone[fn.SharedType] = true
				fmt.Fprintf(&body, "// %s is the shared row type of select %q (spec §selects-over-groups rule 7):\n// one wire type, every member of the target a source.\n", fn.SharedType, lowerFirstWord(fn.MethodSuffix))
				fmt.Fprintf(&body, "type %s struct {\n", fn.SharedType)
				var rows align.Block
				for _, f := range cols {
					// The shared type carries default tags and no per-table
					// notes (A.5, §selects-over-groups rule 7).
					fieldImports(imports, f.goType)
					rows.Row(f.goField, f.goType, fmt.Sprintf("`db:%q json:%q`", f.colName, f.colName))
				}
				rows.WriteTo(&body, "\t")
				body.WriteString("}\n\n")
				rowScanEmit(&body, fn.SharedType, cols)
			}
		case len(fn.Excluded) > 0:
			row := t.model + fn.MethodSuffix
			fmt.Fprintf(&body, "// %s is %s minus (%s) — a struct derivative of select %q,\n// every kept field copied verbatim (spec §selects-over-groups rule 7).\n",
				row, t.model, strings.Join(fn.Excluded, ", "), lowerFirstWord(fn.MethodSuffix))
			fmt.Fprintf(&body, "type %s struct {\n", row)
			var rows align.Block
			for _, f := range cols {
				fieldImports(imports, f.goType)
				if note := settingNote(f.col.Settings); note != "" {
					commentLines(&rows, note)
				}
				rows.Row(f.goField, f.goType, "`"+f.tag+"`")
			}
			rows.WriteTo(&body, "\t")
			body.WriteString("}\n\n")
			rowScanEmit(&body, row, cols)
		}
		selectEmit(&body, t, fn, cols)
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by nao gen from %s; DO NOT EDIT.\n", opts.Source)
	out.WriteString("//\n// Selects declared in the schema (docs/spec.md §selects-over-groups): one method per\n// group member, statically typed, prepare-validated.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", opts.Package)
	paths := make([]string, 0, len(imports))
	for imp := range imports {
		paths = append(paths, imp)
	}
	sort.Strings(paths)
	out.WriteString("import (\n")
	for _, imp := range paths {
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.WriteString(body.String())

	return align.Finish(out.String()), nil
}

// selectColumns resolves one instantiation's projected columns
// (§selects-over-groups rule 7): the explicit list in declared order, the member's fields
// minus the star exclusions, or every field.
func selectColumns(t *tableModel, fn SelectFn) ([]*fieldPlan, error) {
	switch {
	case len(fn.Cols) > 0:
		out := make([]*fieldPlan, 0, len(fn.Cols))
		for _, c := range fn.Cols {
			f := t.field(c)
			if f == nil {
				return nil, fmt.Errorf("select %s: no column %q in table %s", fn.MethodSuffix, c, t.sqlName)
			}
			out = append(out, f)
		}
		return out, nil
	case len(fn.Excluded) > 0:
		ex := make(map[string]bool, len(fn.Excluded))
		for _, c := range fn.Excluded {
			if t.field(c) == nil {
				return nil, fmt.Errorf("select %s: no column %q in table %s", fn.MethodSuffix, c, t.sqlName)
			}
			ex[c] = true
		}
		var out []*fieldPlan
		for _, f := range t.fields {
			if !ex[f.colName] {
				out = append(out, f)
			}
		}
		if len(out) == 0 {
			return nil, fmt.Errorf("select %s: every column of %s excluded", fn.MethodSuffix, t.sqlName)
		}
		return out, nil
	}
	return t.fields, nil
}

// fieldImports records the imports a copied field type drags in.
func fieldImports(imports map[string]bool, goType string) {
	if strings.Contains(goType, "rt.") {
		imports[rtImport] = true
	}
	if strings.Contains(goType, "time.Time") {
		imports["time"] = true
	}
	if strings.Contains(goType, "json.RawMessage") {
		imports["encoding/json"] = true
	}
}

// rowScanEmit writes the scan function for a minted row type, the same
// shape queries.go emits for models.
func rowScanEmit(b *strings.Builder, row string, cols []*fieldPlan) {
	lower := argName(row)
	fmt.Fprintf(b, "func %sScan(r rowScanner) (%s, error) {\n\tvar v %s\n\terr := r.Scan(", lower, row, row)
	for i, f := range cols {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "&v.%s", f.goField)
	}
	b.WriteString(")\n\treturn v, err\n}\n\n")
}

// SelectSQL renders the statement for one instantiation.
func SelectSQL(t *tableModel, fn SelectFn) string {
	cols, err := selectColumns(t, fn)
	if err != nil {
		// The checker refuses such an instantiation (§selects-over-groups rule 7).
		return "-- " + err.Error()
	}
	names := make([]string, len(cols))
	for i, f := range cols {
		names[i] = sqlIdentQuote(f.colName)
	}
	sql := "SELECT " + strings.Join(names, ", ") + " FROM " + sqlIdentQuote(t.sqlName)
	if fn.WhereSQL != "" {
		sql += " WHERE " + fn.WhereSQL
	}
	if fn.OrderSQL != "" {
		sql += " ORDER BY " + fn.OrderSQL
	}
	return sql
}

// SelectSQLFor is SelectSQL keyed the way callers outside the package
// see tables; it builds the plan itself. Test helper.
func SelectSQLFor(f *ast.File, info *check.Info, fn SelectFn) (string, error) {
	return PlanBuild(f, info).SelectStatement(fn)
}

// SelectRowType names the row type one instantiation returns (§selects-over-groups rule 7)
// and reports its fields. It plans the whole file.
func SelectRowType(f *ast.File, info *check.Info, fn SelectFn) (string, []FieldSig, error) {
	return PlanBuild(f, info).SelectRowType(fn)
}

// lowerFirstWord echoes a method suffix the way the schema spells the
// select name (Rows -> rows), for doc comments.
func lowerFirstWord(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func selectEmit(b *strings.Builder, t *tableModel, fn SelectFn, cols []*fieldPlan) {
	row, scanPrefix := t.model, argName(t.model)
	switch {
	case fn.SharedType != "":
		row, scanPrefix = fn.SharedType, argName(fn.SharedType)
	case len(fn.Excluded) > 0:
		row = t.model + fn.MethodSuffix
		scanPrefix = argName(row)
	}
	name := t.model + fn.MethodSuffix
	constName := argName(t.model) + fn.MethodSuffix + "SQL"

	fmt.Fprintf(b, "const %s = `%s`\n\n", constName, SelectSQL(t, fn))

	var sig, binds strings.Builder
	for _, prm := range fn.Params {
		fmt.Fprintf(&sig, ", %s %s", prm.GoName, prm.GoType)
		if strings.HasPrefix(prm.GoType, "[]") {
			// A list parameter travels as one JSON array (§selects-over-groups rule 6, decision list-parameters).
			fmt.Fprintf(&binds, ", sql.Named(%q, rt.JSONList(%s))", prm.SQLName, prm.GoName)
			continue
		}
		fmt.Fprintf(&binds, ", sql.Named(%q, %s)", prm.SQLName, prm.GoName)
	}
	fmt.Fprintf(b, "// %s runs the %q select over %s (spec §selects-over-groups).\n", name, lowerFirstWord(fn.MethodSuffix), t.sqlName)
	fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) ([]%s, error) {\n", name, sig.String(), row)
	fmt.Fprintf(b, "\trows, err := q.db.QueryContext(ctx, %s%s)\n", constName, binds.String())
	rowsScanEmit(b, row, scanPrefix)
}
