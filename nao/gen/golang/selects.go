// Select generation (docs/spec.md §V11.6): one typed method per
// (select × group member), over WHERE/ORDER fragments the checker has
// already typed and rendered. The heavy lifting — plans, scan
// functions, quoting — is shared with the CRUD generator.
package golang

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
)

// GenerateSelects renders nao_selects.go for the given instantiations.
// fns must be non-empty; the caller decides whether the file exists.
func GenerateSelects(f *ast.File, info *check.Info, fns []SelectFn, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	p, err := planBuild(f, info)
	if err != nil {
		return nil, err
	}
	byKey := map[string]*tableModel{}
	for _, t := range p.tables {
		byKey[t.ti.Key] = t
	}

	var body strings.Builder
	imports := map[string]bool{"context": true}
	for _, fn := range fns {
		t := byKey[fn.TableKey]
		if t == nil {
			return nil, fmt.Errorf("select %s: no table %q in the plan", fn.MethodSuffix, fn.TableKey)
		}
		if len(fn.Params) > 0 {
			imports["database/sql"] = true
		}
		for _, prm := range fn.Params {
			if strings.HasPrefix(prm.GoType, "time.") {
				imports["time"] = true
			}
		}
		selectEmit(&body, t, fn)
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by nao gen from %s; DO NOT EDIT.\n", opts.Source)
	out.WriteString("//\n// Selects declared in the schema (docs/spec.md §V11): one method per\n// group member, statically typed, prepare-validated.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", opts.Package)
	paths := make([]string, 0, len(imports))
	for imp := range imports {
		paths = append(paths, imp)
	}
	sort.Strings(paths)
	out.WriteString("import (\n")
	for _, imp := range paths {
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.WriteString(body.String())

	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("generated selects do not parse: %w\n%s", err, out.String())
	}
	return src, nil
}

// SelectSQL renders the statement for one instantiation — shared with
// the prepare-validation tests, so what is tested is what ships.
func SelectSQL(t *tableModel, fn SelectFn) string {
	sql := "SELECT " + t.columnList() + " FROM " + sqlIdentQuote(t.sqlName)
	if fn.WhereSQL != "" {
		sql += " WHERE " + fn.WhereSQL
	}
	if fn.OrderSQL != "" {
		sql += " ORDER BY " + fn.OrderSQL
	}
	return sql
}

// SelectSQLFor is SelectSQL keyed the way callers outside the package
// see tables; it builds the plan itself. Test helper.
func SelectSQLFor(f *ast.File, info *check.Info, fn SelectFn) (string, error) {
	p, err := planBuild(f, info)
	if err != nil {
		return "", err
	}
	for _, t := range p.tables {
		if t.ti.Key == fn.TableKey {
			return SelectSQL(t, fn), nil
		}
	}
	return "", fmt.Errorf("no table %q", fn.TableKey)
}

func selectEmit(b *strings.Builder, t *tableModel, fn SelectFn) {
	lower := argName(t.model)
	name := t.model + fn.MethodSuffix
	constName := lower + fn.MethodSuffix + "SQL"

	fmt.Fprintf(b, "const %s = `%s`\n\n", constName, SelectSQL(t, fn))

	var sig, binds strings.Builder
	for _, prm := range fn.Params {
		fmt.Fprintf(&sig, ", %s %s", prm.GoName, prm.GoType)
		fmt.Fprintf(&binds, ", sql.Named(%q, %s)", prm.SQLName, prm.GoName)
	}
	fmt.Fprintf(b, "// %s runs the %q select over %s (spec §V11).\n", name, fn.MethodSuffix, t.sqlName)
	fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) ([]%s, error) {\n", name, sig.String(), t.model)
	fmt.Fprintf(b, "\trows, err := q.db.QueryContext(ctx, %s%s)\n", constName, binds.String())
	rowsScanEmit(b, t.model, lower)
}
