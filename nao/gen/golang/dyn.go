package golang

import (
	"fmt"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/gen/layout"
	"github.com/Piechutowski/volt/lang/ast"
	"github.com/Piechutowski/volt/lang/check"
	"github.com/Piechutowski/volt/nao/naming"
)

// GenerateDyn renders the dynamic-query file for one checked schema file.
func GenerateDyn(f *ast.File, info *check.Info, opts Options) ([]byte, error) {
	return Dyn(naming.PlanBuild(f, info), opts)
}

// Dyn renders the dynamic-query file (volt_dyn.go) for the planned package
// (spec/generated-query-surface).
func Dyn(pl *naming.Plan, opts Options) ([]byte, error) {
	if opts.Package == "" {
		return nil, fmt.Errorf("no package name")
	}
	if err := pl.Err(); err != nil {
		return nil, err
	}
	if err := pl.NameCollisionErr(); err != nil {
		return nil, err
	}
	e := &dynEmitter{tables: pl.Tables(), opts: opts}
	e.run()
	return align.Finish(e.out.String()), nil
}

type dynEmitter struct {
	tables []*naming.Table
	opts   Options
	out    strings.Builder
	body   strings.Builder
}

func (e *dynEmitter) run() {
	e.body.Grow(fieldCount(e.tables)*80 + len(e.tables)*1200)
	for _, t := range e.tables {
		e.tableEmit(t)
	}
	e.header()
	e.out.Grow(e.body.Len())
	e.out.WriteString(e.body.String())
}

func (e *dynEmitter) header() {
	fmt.Fprintf(&e.out, "// Code generated by volt gen from %s. DO NOT EDIT.\n", e.opts.Source)
	e.out.WriteString("\n")
	fmt.Fprintf(&e.out, "package %s\n", e.opts.Package)

	if e.body.Len() == 0 {
		return
	}
	imports := map[string]bool{rtImport: true}
	e.out.WriteString("\nimport (\n")
	for _, p := range importKeysSort(imports) {
		fmt.Fprintf(&e.out, "\t%s\n", importDecl(p))
	}
	e.out.WriteString(")\n\n")
}

func (e *dynEmitter) tableEmit(t *naming.Table) {
	if len(t.Fields) == 0 {
		return
	}
	b := &e.body
	consts := []layout.Spec{
		{Name: t.Names.TableConst, Value: text("`" + t.TableSQL() + "`")},
		{Name: t.Names.ColumnsConst, Value: sqlFragment(t.ColumnList())},
	}
	b.WriteString("const (\n")
	layout.SpecsWrite(b, 1, consts)
	b.WriteString(")\n\n")

	e.wrappersEmit(t)
	e.queryEmit(t)
	e.countEmit(t)
	e.existsEmit(t)
	e.deleteWhereEmit(t)
	e.updateWhereEmit(t)
}

func (e *dynEmitter) wrappersEmit(t *naming.Table) {
	b := &e.body
	m, n := t.Model, &t.Names
	opt := "rt.Opt[" + m + "]"
	funcEmit(b, "func "+n.Limit, []string{"n int64"}, opt, stmt("return ", call("rt.Limit["+m+"]", text("n"))))
	funcEmit(b, "func "+n.Offset, []string{"n int64"}, opt, stmt("return ", call("rt.Offset["+m+"]", text("n"))))
	funcEmit(b, "func "+n.Distinct, nil, opt, text("return rt.Distinct["+m+"]()"))
	orderBy := stmt("return ", calls("rt.OrderBy", "terms..."))
	funcEmit(b, "func "+n.OrderBy, []string{"terms ...rt.Order[" + m + "]"}, opt, orderBy)
	funcEmit(b, "func "+n.After, []string{"key ...any"}, opt, stmt("return ", call("rt.After["+m+"]", text("key..."))))
	assigns := "[]rt.Assign[" + m + "]"
	funcEmit(b, "func "+n.Set, []string{"assigns ..." + assigns[2:]}, assigns, text("return assigns"))
}

func renderedReturn(effect string, scan string) elem {
	keys := []string{"SQL", "Args", "Scan", "Err"}
	return stmt("return ", literal(effect, keys, texts("voltSQL", "voltArgs", scan, "voltErr")...))
}

func rendered(render string, args ...string) elem {
	return stmt("voltSQL, voltArgs, voltErr := ", calls(render, args...))
}

func (e *dynEmitter) queryEmit(t *naming.Table) {
	effect := "rt.Query[" + t.Model + "]"
	funcEmit(&e.body, "func "+t.Names.Query, []string{"opts ...rt.Opt[" + t.Model + "]"}, effect,
		rendered("rt.SelectRender", t.Names.TableConst, t.Names.ColumnsConst, "opts..."),
		renderedReturn(effect, t.Names.Scan))
}

func (e *dynEmitter) countEmit(t *naming.Table) {
	funcEmit(&e.body, "func "+t.Names.Count, []string{"preds ...rt.Pred[" + t.Model + "]"}, "rt.Lookup[int64]",
		rendered("rt.CountRender", t.Names.TableConst, "preds"),
		renderedReturn("rt.Lookup[int64]", "rt.ScanOne[int64]"))
}

func (e *dynEmitter) existsEmit(t *naming.Table) {
	funcEmit(&e.body, "func "+t.Names.Exists, []string{"preds ...rt.Pred[" + t.Model + "]"}, "rt.Lookup[bool]",
		rendered("rt.ExistsRender", t.Names.TableConst, "preds"),
		renderedReturn("rt.Lookup[bool]", "rt.ScanOne[bool]"))
}

func execReturn() elem {
	keys := []string{"SQL", "Args", "Err"}
	return stmt("return ", literal("rt.Exec", keys, texts("voltSQL", "voltArgs", "voltErr")...))
}

func (e *dynEmitter) deleteWhereEmit(t *naming.Table) {
	funcEmit(&e.body, "func "+t.Names.DeleteWhere, []string{"preds ...rt.Pred[" + t.Model + "]"}, "rt.Exec",
		rendered("rt.DeleteRender", t.Names.TableConst, "preds"), execReturn())
}

func (e *dynEmitter) updateWhereEmit(t *naming.Table) {
	params := []string{"set []rt.Assign[" + t.Model + "]", "preds ...rt.Pred[" + t.Model + "]"}
	funcEmit(&e.body, "func "+t.Names.UpdateWhere, params, "rt.Exec",
		rendered("rt.UpdateRender", t.Names.TableConst, "set", "preds"), execReturn())
}
