// Package router generates the Volt router files for one checked
// package (spec Part II, router spec/common-syntactic-forms): volt_handlers.go (controller
// interfaces + the NewRouter constructor), volt_router.go (ServeMux
// registrations with typed shims and statically composed pipelines),
// volt_paths.go (typed reverse-URL helpers) and volt_routes.go (the
// introspectable route table). The output is gofmt-canonical by
// construction; generated code imports the standard library and
// the volt runtime package only.
package router

import (
	"fmt"
	"go/token"
	"sort"
	"strconv"
	"strings"

	"github.com/Piechutowski/volt/gen/align"
	"github.com/Piechutowski/volt/gen/layout"
	"github.com/Piechutowski/volt/internal/par"
	"github.com/Piechutowski/volt/lang"
	"github.com/Piechutowski/volt/nao/naming"
)

const (
	voltImport = "github.com/Piechutowski/volt"
	runImport  = "github.com/Piechutowski/volt/nao/run"
	rtImport   = "github.com/Piechutowski/volt/nao/rt"
)

// Options configures generation.
type Options struct {
	// Source names the input (the package path), recorded in headers.
	Source string
	// Package overrides the package clause of the router files; empty
	// means the Volt package's name (spec/projects-and-packages).
	Package string
	// ClientBeside writes the client beside the models instead of as a
	// client subpackage (spec/generated-client): ClientBesideFile in package Package,
	// NewClient as the constructor.
	ClientBeside bool
}

// Files are the generated file names, in emission order. The client
// package (spec/generated-client) lives in a subdirectory of the routing package.
var Files = []string{"volt_handlers.go", "volt_router.go", "volt_paths.go", "volt_routes.go", ClientFile}

// ClientFile is the generated client package's file, relative to the
// routing package directory.
const ClientFile = "client/volt_client.go"

// ClientBesideFile is the client written beside the models by
// Options.ClientBeside, in place of ClientFile.
const ClientBesideFile = "volt_client.go"

// Generate renders the four router files for one checked package. The
// package must be free of check errors and contain routing elements.
func Generate(pkg *lang.Package, opts Options) (map[string][]byte, error) {
	if !pkg.HasRouting() {
		return nil, fmt.Errorf("package %s declares no routing elements", pkg.Path)
	}
	type emit struct {
		name string
		fn   func(*generator) error
	}
	emits := []emit{
		{"volt_handlers.go", (*generator).handlersEmit},
		{"volt_router.go", (*generator).routerEmit},
		{"volt_paths.go", (*generator).pathsEmit},
		{"volt_routes.go", (*generator).routesEmit},
	}
	switch {
	case opts.ClientBeside:
		emits = append(emits, emit{ClientBesideFile, (*generator).clientEmit})
	case !(&generator{pkg: pkg, opts: opts}).clientOmitted():
		emits = append(emits, emit{ClientFile, (*generator).clientEmit})
	}
	codes := make([][]byte, len(emits))
	errs := make([]error, len(emits))
	par.For(len(emits), func(i int) {
		g := &generator{pkg: pkg, opts: opts}
		g.out.Grow(len(pkg.Routes) * routeBytes[emits[i].name])
		if errs[i] = emits[i].fn(g); errs[i] == nil {
			codes[i] = align.Finish(g.out.String())
		}
	})
	out := map[string][]byte{}
	for i, e := range emits {
		if errs[i] != nil {
			return nil, errs[i]
		}
		out[e.name] = codes[i]
	}
	return out, nil
}

type generator struct {
	pkg    *lang.Package
	opts   Options
	out    strings.Builder
	pkgDoc bool
}

func (g *generator) pf(format string, args ...any) {
	fmt.Fprintf(&g.out, format, args...)
}

func (g *generator) header(imports ...string) {
	g.headerFor(g.pkgName(), imports...)
}

func (g *generator) pkgName() string {
	if g.opts.Package != "" {
		return g.opts.Package
	}
	return g.pkg.Name
}

func (g *generator) headerFor(pkgName string, imports ...string) {
	g.pf("// Code generated by volt gen from %s. DO NOT EDIT.\n\n", g.opts.Source)
	if g.pkgDoc {
		g.docWrite("", g.pkg.Doc())
	}
	g.pf("package %s\n\n", pkgName)
	groups := importGroups(imports)
	if len(groups) > 0 {
		g.pf("import (\n")
		for i, group := range groups {
			if i > 0 {
				g.pf("\n")
			}
			for _, im := range group {
				if strings.Contains(im, " ") {
					g.pf("\t%s\n", im)
					continue
				}
				g.pf("\t%q\n", im)
			}
		}
		g.pf(")\n\n")
	}
}

func importGroups(imports []string) [][]string {
	var groups [][]string
	var cur []string
	flush := func() {
		if len(cur) == 0 {
			return
		}
		sort.SliceStable(cur, func(i, j int) bool { return importPath(cur[i]) < importPath(cur[j]) })
		groups = append(groups, cur)
		cur = nil
	}
	for _, im := range imports {
		if im == "" {
			flush()
			continue
		}
		cur = append(cur, im)
	}
	flush()
	return groups
}

func importPath(im string) string {
	if i := strings.IndexByte(im, ' '); i >= 0 {
		return strings.Trim(im[i+1:], `"`)
	}
	return im
}

func (g *generator) dataPackages() []*lang.QueryRef {
	seen := map[string]*lang.QueryRef{}
	for _, r := range g.pkg.Routes {
		if r.Query != nil && seen[r.Query.Qualifier] == nil {
			seen[r.Query.Qualifier] = r.Query
		}
	}
	quals := make([]string, 0, len(seen))
	for q := range seen {
		quals = append(quals, q)
	}
	sort.Strings(quals)
	out := make([]*lang.QueryRef, len(quals))
	for i, q := range quals {
		out[i] = seen[q]
	}
	return out
}

// clientPackages lists the data packages the client's methods name: the
// query routes' and the changeset bodies of controller routes
// (spec/request-bodies), one per qualifier, in order.
func (g *generator) clientPackages() []*lang.QueryRef {
	seen := map[string]*lang.QueryRef{}
	for _, r := range g.pkg.Routes {
		if r.ClientName == "" {
			continue
		}
		if r.Query != nil && seen[r.Query.Qualifier] == nil {
			seen[r.Query.Qualifier] = r.Query
		}
		if b := r.Body; b != nil && b.Kind == lang.BodyChangeset && seen[b.Query.Qualifier] == nil {
			seen[b.Query.Qualifier] = b.Query
		}
	}
	quals := make([]string, 0, len(seen))
	for q := range seen {
		quals = append(quals, q)
	}
	sort.Strings(quals)
	out := make([]*lang.QueryRef, len(quals))
	for i, q := range quals {
		out[i] = seen[q]
	}
	return out
}

func (g *generator) clientOmitted() bool {
	if g.pkg.Name != "main" {
		return false
	}
	for _, q := range g.dataPackages() {
		if q.Local {
			return true
		}
	}
	return false
}

func dataImport(q *lang.QueryRef) string {
	return importSpell(q.Qualifier, q.PkgName, q.Import)
}

func importSpell(qual, pkgName, path string) string {
	if qual == pkgName && qual == path[strings.LastIndex(path, "/")+1:] {
		return path
	}
	return qual + " " + fmt.Sprintf("%q", path)
}

func (g *generator) controllerNames() []string {
	names := make([]string, 0, len(g.pkg.Controllers))
	for n := range g.pkg.Controllers {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func fullPattern(r *lang.RouteInfo) string {
	if r.Method == "" {
		return r.Pattern
	}
	return r.Method + " " + r.Pattern
}

func pipeKey(pipes []string) string { return strings.Join(pipes, ",") }

func (g *generator) timeParams() bool {
	for _, r := range g.pkg.Routes {
		if r.Timeout > 0 {
			return true
		}
	}
	if g.queryTimeParams() {
		return true
	}
	for _, r := range g.pkg.Routes {
		for _, ld := range r.Loads {
			for _, p := range ld.Query.Params {
				bound := p.Source != lang.FromPath && p.Source != lang.FromLiteral
				if bound && strings.TrimPrefix(p.GoType, "[]") == "time.Time" {
					return true
				}
			}
		}
	}
	return false
}

// clientParams are the parameters the client's methods take in the
// query string (spec/generated-client): a query route's and the keys
// the loads of a controller route bind.
func (g *generator) clientParams() []lang.QueryParam {
	var out []lang.QueryParam
	for _, r := range g.pkg.Routes {
		switch {
		case r.ClientName == "" || r.Events:
		case r.Query != nil:
			for _, p := range r.Query.Params {
				if p.Source == lang.FromQuery || p.Source == lang.FromList {
					out = append(out, p)
				}
			}
		default:
			out = append(out, loadKeys(r)...)
		}
	}
	return out
}

func (g *generator) queryOptionalParams() bool {
	for _, p := range g.clientParams() {
		if p.Optional {
			return true
		}
	}
	return false
}

func (g *generator) clientTimeParams() bool {
	for _, p := range g.clientParams() {
		if strings.TrimPrefix(p.GoType, "[]") == "time.Time" {
			return true
		}
	}
	return false
}

func (g *generator) queryTimeParams() bool {
	for _, r := range g.pkg.Routes {
		if r.Query == nil {
			continue
		}
		for _, p := range r.Query.Params {
			if strings.TrimPrefix(p.GoType, "[]") == "time.Time" {
				return true
			}
		}
	}
	return false
}

func (g *generator) routerEmit() error {
	g.pkgDoc = !g.pkg.HasSchema()
	imports := []string{"net/http"}
	if g.timeParams() {
		imports = append(imports, "time")
	}
	imports = append(imports, "", voltImport, runImport)
	seen := map[string]bool{}
	for _, q := range append(g.dataPackages(), g.loadPackages()...) {
		if !q.Local && !seen[q.Qualifier] {
			seen[q.Qualifier] = true
			imports = append(imports, dataImport(q))
		}
	}
	imports = append(imports, g.scopeLoadImports(imports)...)
	g.header(imports...)

	g.pf("func register(mux *http.ServeMux, c Controllers) {\n")
	g.pf("\tvoltPerform := run.Performer(c.DB)\n")
	g.pf("\tfor _, route := range voltRegistrations {\n")
	g.pf("\t\tmux.Handle(route.pattern, route.handler(c, voltPerform))\n")
	g.pf("\t}\n")
	g.pf("}\n\n")
	g.pf("var voltRegistrations = []struct {\n")
	g.pf("\tpattern string\n")
	g.pf("\thandler func(Controllers, volt.Performer) http.Handler\n")
	g.pf("}{\n")
	for i, r := range g.pkg.Routes {
		values := texts(strconv.Quote(fullPattern(r)), "voltRoute"+strconv.Itoa(i))
		g.line(1, "", layout.Fields("{", []string{"pattern", "handler"}, values, "}"), ",")
	}
	g.pf("}\n")

	ehs := map[string]bool{}
	for _, r := range g.pkg.Routes {
		if r.ErrorHandler != "" {
			ehs[r.ErrorHandler] = true
		}
	}
	ehNames := make([]string, 0, len(ehs))
	for n := range ehs {
		ehNames = append(ehNames, n)
	}
	sort.Strings(ehNames)

	for i, r := range g.pkg.Routes {
		g.routeEmit(i, r)
	}
	g.pf("\n")

	for _, n := range ehNames {
		g.line(0, "var errHandler"+n+" = ", calls("volt.ErrorHandler", n), "\n")
	}
	return nil
}

func (g *generator) hasEvents() bool {
	for _, r := range g.pkg.Routes {
		if r.Events {
			return true
		}
	}
	return false
}

func pathExpr(r *lang.RouteInfo) layout.Elem { return pathExprNamed(r, nil) }

// pathExprNamed is the path of r built from its parameters, each under
// the Go name names gives it, its GoName when names has none.
func pathExprNamed(r *lang.RouteInfo, names map[string]string) layout.Elem {
	if r.Pattern == "/{$}" {
		return text(`"/"`)
	}
	var parts []string
	lit := ""
	flushLit := func() {
		if lit != "" {
			parts = append(parts, fmt.Sprintf("%q", lit))
			lit = ""
		}
	}
	byName := map[string]lang.Param{}
	for _, p := range r.Params {
		if n := names[p.Name]; n != "" {
			p.GoName = n
		}
		byName[p.Name] = p
	}
	for _, seg := range strings.Split(strings.TrimPrefix(r.Pattern, "/"), "/") {
		switch {
		case strings.HasPrefix(seg, "{"):
			name := strings.TrimSuffix(strings.TrimPrefix(seg, "{"), "}")
			name = strings.TrimSuffix(name, "...")
			p := byName[name]
			lit += "/"
			flushLit()
			switch {
			case p.Wild:
				parts = append(parts, "volt.SegWild("+p.GoName+")")
			case p.Type == lang.TString:
				parts = append(parts, "volt.Seg("+p.GoName+")")
			default:
				parts = append(parts, "volt.SegInt("+p.GoName+")")
			}
		default:
			lit += "/" + seg
		}
	}
	flushLit()
	return layout.Concat(parts)
}

// loadKeys are the query-string keys the loads of a controller route
// bind (spec/route-loads, spec/generated-client), each once, in the order
// the loads first read it, typed as its bindings, which the checker holds
// to one type, and required when any binding of the key requires it.
func loadKeys(r *lang.RouteInfo) []lang.QueryParam {
	var out []lang.QueryParam
	at := map[string]int{}
	for _, ld := range r.Loads {
		for _, p := range ld.Query.Params {
			if p.Source != lang.FromQuery && p.Source != lang.FromList {
				continue
			}
			if i, seen := at[p.Name]; seen {
				if out[i].Optional && !p.Optional {
					out[i] = p
				}
				continue
			}
			at[p.Name] = len(out)
			out = append(out, p)
		}
	}
	return out
}

// clientNames hands out the Go parameter names of one client method
// (spec/generated-client): each name wanted, with _ appended while it
// is a Go keyword, a name the method's own code uses, the qualifier the
// client imports a data package under, one of the generated locals' form
// or a name an earlier parameter of the method took.
type clientNames struct{ taken map[string]bool }

func (g *generator) clientNamesNew() clientNames {
	taken := map[string]bool{}
	if !g.opts.ClientBeside {
		for _, q := range g.clientPackages() {
			taken[clientQualifier(q)] = true
		}
	}
	return clientNames{taken}
}

func (n clientNames) name(want string) string {
	name := want
	for token.IsKeyword(name) || clientMethodNames[name] || naming.LocalName(name) || n.taken[name] {
		name += "_"
	}
	n.taken[name] = true
	return name
}

var clientMethodNames = map[string]bool{"ctx": true, "c": true, "cs": true, "body": true, "volt": true, "http": true, "context": true, "rt": true, "time": true, "nil": true, "append": true, "any": true, "error": true}

// clientOwnImports are the names the client imports a package of the
// standard library or the runtime under (spec/generated-client).
var clientOwnImports = map[string]bool{"context": true, "http": true, "rt": true, "time": true}

// clientQualifier is the name the client imports the data package of q
// under (spec/generated-client): its import qualifier, which spec/imports
// keeps off the client's own imports, or for a package that routes its
// own tables its name, as volt and the name with an upper-case initial
// when the client imports a package of that name for itself.
func clientQualifier(q *lang.QueryRef) string {
	if q.Local && clientOwnImports[q.Qualifier] {
		return "volt" + strings.ToUpper(q.Qualifier[:1]) + q.Qualifier[1:]
	}
	return q.Qualifier
}

func clientImport(q *lang.QueryRef) string {
	return importSpell(clientQualifier(q), q.PkgName, q.Import)
}

// clientType spells the type name of the data package of q in the
// client: bare beside the models, qualified as clientQualifier says
// otherwise.
func (g *generator) clientType(q *lang.QueryRef, name string) string {
	if g.opts.ClientBeside {
		return name
	}
	return clientQualifier(q) + "." + name
}

func zeroArgs(ps []lang.Param) []string {
	out := make([]string, len(ps))
	for i, p := range ps {
		out[i] = "0"
		if p.Type == lang.TString {
			out[i] = `""`
		}
	}
	return out
}

func (g *generator) queryResult(q *lang.QueryRef) string {
	if q.Result == "" {
		return "int64"
	}
	result := q.Result
	if !q.Local {
		result = q.Qualifier + "." + result
	}
	if q.Many {
		result = "[]" + result
	}
	return result
}

// loadPackages lists the data packages the loads and the changeset
// bodies of controller routes bind, one per qualifier, in order.
func (g *generator) loadPackages() []*lang.QueryRef {
	seen := map[string]*lang.QueryRef{}
	for _, r := range g.pkg.Routes {
		if b := r.Body; b != nil && b.Kind == lang.BodyChangeset && !b.Query.Local && seen[b.Query.Qualifier] == nil {
			seen[b.Query.Qualifier] = b.Query
		}
		for _, ld := range r.Loads {
			if !ld.Query.Local && seen[ld.Query.Qualifier] == nil {
				seen[ld.Query.Qualifier] = ld.Query
			}
		}
	}
	quals := make([]string, 0, len(seen))
	for q := range seen {
		quals = append(quals, q)
	}
	sort.Strings(quals)
	out := make([]*lang.QueryRef, len(quals))
	for i, q := range quals {
		out[i] = seen[q]
	}
	return out
}

func zeroLoads(ls []lang.LoadInfo) []string {
	out := make([]string, len(ls))
	for i, ld := range ls {
		out[i] = ld.GoType() + "{}"
		if ld.Query.Many {
			out[i] = "nil"
		}
	}
	return out
}

func zeroBody(b *lang.BodyInfo) []string {
	if b == nil {
		return nil
	}
	if b.Kind == lang.BodyChangeset {
		ctor := strings.TrimSuffix(b.Query.Changeset.Type, "Changeset") + "New"
		if !b.Query.Local {
			ctor = b.Query.Qualifier + "." + ctor
		}
		return []string{ctor + "()"}
	}
	return []string{b.GoType() + "{}"}
}

func zeroScopeLoads(ls []lang.ScopeLoad) []string {
	out := make([]string, len(ls))
	for i, sl := range ls {
		out[i] = "*new(" + sl.GoType + ")"
	}
	return out
}

// scopeLoadImports lists the imports the scope loads' types need beyond
// the ones already listed, one per qualifier, in order.
func (g *generator) scopeLoadImports(have []string) []string {
	seen := map[string]bool{}
	for _, im := range have {
		seen[importPath(im)] = true
	}
	var out []string
	for _, r := range g.pkg.Routes {
		for _, sl := range r.ScopeLoads {
			if sl.Import == "" || seen[sl.Import] {
				continue
			}
			seen[sl.Import] = true
			out = append(out, importSpell(sl.Qualifier, sl.PkgName, sl.Import))
		}
	}
	sort.Strings(out)
	return out
}

func (g *generator) docWrite(indent, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		if line == "" {
			g.pf("%s//\n", indent)
			continue
		}
		g.pf("%s// %s\n", indent, line)
	}
}
