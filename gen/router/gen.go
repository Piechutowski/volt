// Package router generates the Volt router files for one checked
// package (spec §V, router spec §4): volt_handlers.go (controller
// interfaces + the New constructor), volt_router.go (ServeMux
// registrations with typed shims and statically composed pipelines),
// volt_paths.go (typed reverse-URL helpers) and volt_routes.go (the
// introspectable route table).
//
// All output passes through go/format.Source, so the generator cannot
// emit code that does not parse, and the result is gofmt-clean by
// construction. Generated code imports the standard library and the
// volt runtime package only.
package router

import (
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/Piechutowski/volt/lang"
)

// voltImport is the runtime package generated code depends on.
const voltImport = "github.com/Piechutowski/volt"

// Options configures generation.
type Options struct {
	// Source names the input (the package path), recorded in headers.
	Source string
}

// Files are the generated file names, in emission order. The client
// package (§V4.10) lives in a subdirectory of the routing package.
var Files = []string{"volt_handlers.go", "volt_router.go", "volt_paths.go", "volt_routes.go", ClientFile}

// ClientFile is the generated client package's file, relative to the
// routing package directory.
const ClientFile = "client/volt_client.go"

// Generate renders the four router files for one checked package. The
// package must be free of check errors and contain routing elements.
func Generate(pkg *lang.Package, opts Options) (map[string][]byte, error) {
	if !pkg.HasRouting() {
		return nil, fmt.Errorf("package %s declares no routing elements", pkg.Path)
	}
	g := &generator{pkg: pkg, opts: opts}
	out := map[string][]byte{}
	for name, emit := range map[string]func() error{
		"volt_handlers.go": g.handlersEmit,
		"volt_router.go":   g.routerEmit,
		"volt_paths.go":    g.pathsEmit,
		"volt_routes.go":   g.routesEmit,
		ClientFile:         g.clientEmit,
	} {
		g.out.Reset()
		if err := emit(); err != nil {
			return nil, err
		}
		src, err := format.Source([]byte(g.out.String()))
		if err != nil {
			// unreachable if the emitter is correct; surfaced loudly if not
			return nil, fmt.Errorf("generated %s does not parse: %w\n%s", name, err, g.out.String())
		}
		out[name] = src
	}
	return out, nil
}

type generator struct {
	pkg      *lang.Package
	opts     Options
	out      strings.Builder
	pipeVars map[string]string // pipe sequence key -> composed var name
}

func (g *generator) pf(format string, args ...any) {
	fmt.Fprintf(&g.out, format, args...)
}

func (g *generator) header(imports ...string) {
	g.headerFor(g.pkg.Name, "", imports...)
}

// headerFor is header for a named package with an optional package doc.
func (g *generator) headerFor(pkgName, doc string, imports ...string) {
	g.pf("// Code generated by volt gen. DO NOT EDIT.\n")
	g.pf("//\n// Source: %s\n\n", g.opts.Source)
	if doc != "" {
		g.pf("%s", doc)
	}
	g.pf("package %s\n\n", pkgName)
	if len(imports) > 0 {
		g.pf("import (\n")
		for _, im := range imports {
			if im == "" {
				g.pf("\n") // group separator
				continue
			}
			if strings.Contains(im, " ") {
				g.pf("\t%s\n", im) // already rendered: `alias "path"`
				continue
			}
			g.pf("\t%q\n", im)
		}
		g.pf(")\n\n")
	}
}

// dataPackages lists the imported data packages query routes go
// through, by qualifier, sorted (§V4.8).
func (g *generator) dataPackages() []*lang.QueryRef {
	seen := map[string]*lang.QueryRef{}
	for _, r := range g.pkg.Routes {
		if r.Query != nil && seen[r.Query.Qualifier] == nil {
			seen[r.Query.Qualifier] = r.Query
		}
	}
	quals := make([]string, 0, len(seen))
	for q := range seen {
		quals = append(quals, q)
	}
	sort.Strings(quals)
	out := make([]*lang.QueryRef, len(quals))
	for i, q := range quals {
		out[i] = seen[q]
	}
	return out
}

// dataImport renders the import line of a data package: aliased when
// the Volt qualifier differs from the Go package name.
func dataImport(q *lang.QueryRef) string {
	if q.Qualifier == q.PkgName {
		return q.Import
	}
	return q.Qualifier + " " + fmt.Sprintf("%q", q.Import)
}

// handlerLabel renders a route's handler for comments: Controller.Action
// or pkg.Query.
func handlerLabel(r *lang.RouteInfo) string { return r.HandlerRef() }

// controllerNames returns the controllers sorted by name for
// deterministic emission.
func (g *generator) controllerNames() []string {
	names := make([]string, 0, len(g.pkg.Controllers))
	for n := range g.pkg.Controllers {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

// fullPattern is the ServeMux registration string: "METHOD /path", or
// just "/path" for the any-verb.
func fullPattern(r *lang.RouteInfo) string {
	if r.Method == "" {
		return r.Pattern
	}
	return r.Method + " " + r.Pattern
}

// sigParams renders the typed parameter list of an action, after
// (w, r): ", id int32, path string".
func sigParams(ps []lang.Param) string {
	var b strings.Builder
	for _, p := range ps {
		b.WriteString(", " + p.GoName + " " + p.Type.GoType())
	}
	return b.String()
}

/* ===== volt_handlers.go ===== */

func (g *generator) handlersEmit() error {
	imports := []string{"net/http", "", voltImport}
	data := g.dataPackages()
	for _, q := range data {
		imports = append(imports, dataImport(q))
	}
	g.header(imports...)

	for _, name := range g.controllerNames() {
		ci := g.pkg.Controllers[name]
		g.pf("// %sController is implemented by your code and wired through\n", name)
		g.pf("// Controllers; a route referencing %s.<Action> will not build until\n", name)
		g.pf("// the method exists with this exact signature.\n")
		g.pf("type %sController interface {\n", name)
		for _, a := range ci.Actions {
			for _, r := range a.Routes {
				g.pf("\t// %s handles %s %s\n", a.Name, methodOrAny(r.Method), r.Spelled)
			}
			g.pf("\t%s(w http.ResponseWriter, r *volt.Request%s) error\n", a.Name, sigParams(a.Params))
		}
		g.pf("}\n\n")
	}

	g.pf("// Controllers is the dependency manifest of the route table: one\n")
	g.pf("// implementation per controller named in the routes")
	if len(data) > 0 {
		g.pf(", and the\n// Queries handle of every data package query routes go through (§V4.8)")
	}
	g.pf(".\n")
	g.pf("type Controllers struct {\n")
	for _, name := range g.controllerNames() {
		g.pf("\t%s %sController\n", name, name)
	}
	for _, q := range data {
		g.pf("\t%s *%s.Queries // query routes written %s.<Method>\n", q.Field, q.Qualifier, q.Qualifier)
	}
	g.pf("}\n\n")

	g.pf("// New builds the router: ServeMux registrations with statically\n")
	g.pf("// composed pipelines. The result is a plain http.Handler.\n")
	g.pf("func New(c Controllers) http.Handler {\n")
	g.pf("\tmux := http.NewServeMux()\n")
	g.pf("\tregister(mux, c)\n")
	g.pf("\treturn mux\n")
	g.pf("}\n")
	return nil
}

/* ===== volt_router.go ===== */

// pipeKey joins a pipe sequence for dedup. Pipeline names are plain
// identifiers (§V3.1), so "," cannot occur inside one and the key is
// collision-free.
func pipeKey(pipes []string) string { return strings.Join(pipes, ",") }

// plugExpr renders one pipeline entry as a Go expression.
func plugExpr(ref string, pkgName string) string {
	// self-qualified references collapse to the bare name: the generated
	// file lives in the same Go package as the middleware.
	if rest, ok := strings.CutPrefix(ref, pkgName+"."); ok {
		return rest
	}
	return ref
}

func (g *generator) routerEmit() error {
	imports := []string{"net/http", "", voltImport}
	for _, q := range g.dataPackages() {
		// The shim names the package only for a body type it declares.
		for _, r := range g.pkg.Routes {
			if r.Query != nil && r.Query.Qualifier == q.Qualifier && hasBody(r.Query) {
				imports = append(imports, dataImport(q))
				break
			}
		}
	}
	g.header(imports...)

	g.pf("// register wires every route of the package onto mux. Dispatch is\n")
	g.pf("// decided here, at generation time: the route line and the call it\n")
	g.pf("// makes are emitted together and cannot disagree.\n")
	g.pf("func register(mux *http.ServeMux, c Controllers) {\n")

	// Composed pipelines: one indexed var per distinct sequence, in
	// first-use order. Index-based names cannot collide, whatever the
	// pipeline names are.
	g.pipeVars = map[string]string{}
	var seqs [][]string
	for _, r := range g.pkg.Routes {
		key := pipeKey(r.Pipes)
		if len(r.Pipes) == 0 || g.pipeVars[key] != "" {
			continue
		}
		g.pipeVars[key] = fmt.Sprintf("pipe%d", len(seqs))
		seqs = append(seqs, r.Pipes)
	}
	for _, pipes := range seqs {
		var plugs []string
		for _, name := range pipes {
			pl := g.pkg.Pipelines[name]
			for _, plug := range pl.Plugs {
				plugs = append(plugs, plugExpr(plug.Ref.String(), g.pkg.Name))
			}
		}
		g.pf("\t// pipeline %s: %s\n", strings.Join(pipes, " + "), strings.Join(plugs, ", "))
		g.pf("\t%s := func(h http.Handler) http.Handler {\n", g.pipeVars[pipeKey(pipes)])
		g.pf("\t\treturn volt.Chain(h%s)\n", prefixEach(plugs, ", "))
		g.pf("\t}\n")
	}
	if len(seqs) > 0 {
		g.pf("\n")
	}

	// Error-handler adapters, one per distinct handler, sorted.
	ehs := map[string]bool{}
	for _, r := range g.pkg.Routes {
		if r.ErrorHandler != "" {
			ehs[r.ErrorHandler] = true
		}
	}
	ehNames := make([]string, 0, len(ehs))
	for n := range ehs {
		ehNames = append(ehNames, n)
	}
	sort.Strings(ehNames)

	for _, r := range g.pkg.Routes {
		g.routeEmit(r)
	}
	g.pf("}\n\n")

	for _, n := range ehNames {
		g.pf("// errHandler%s adapts the error_handler declared in the routes.\n", n)
		g.pf("var errHandler%s = volt.ErrorHandler(%s)\n", n, n)
	}
	return nil
}

func prefixEach(items []string, sep string) string {
	var b strings.Builder
	for _, it := range items {
		b.WriteString(sep + it)
	}
	return b.String()
}

// hasBody reports whether a query route decodes a request body.
func hasBody(q *lang.QueryRef) bool {
	for _, p := range q.Params {
		if p.Source == lang.FromBody {
			return true
		}
	}
	return false
}

// pathParse renders the typed parse of one path parameter into the
// shim body, returning the expression that carries its value (§V4.1.3:
// a parse failure is the route's 404).
func pathParse(body *strings.Builder, p lang.Param) string {
	if p.Type == lang.TString {
		// Wildcards and string params pass through verbatim.
		return fmt.Sprintf("r.PathValue(%q)", p.Name)
	}
	parse := map[lang.ParamType]string{
		lang.TInt: "ParseInt", lang.TInt32: "ParseInt32", lang.TInt64: "ParseInt64",
	}[p.Type]
	fmt.Fprintf(body, "\t\tvolt%s, ok := volt.%s(r.PathValue(%q))\n", p.GoName, parse, p.Name)
	fmt.Fprintf(body, "\t\tif !ok {\n\t\t\treturn volt.ErrNotFound\n\t\t}\n")
	return "volt" + p.GoName
}

// queryShimBody renders a query route's generated handler (§V4.8): bind
// every parameter from its source, call the query, render the result.
func queryShimBody(r *lang.RouteInfo) string {
	q := r.Query
	var body strings.Builder
	byName := map[string]lang.Param{}
	for _, p := range r.Params {
		byName[p.Name] = p
	}
	args := make([]string, 0, len(q.Params))
	for _, p := range q.Params {
		switch p.Source {
		case lang.FromPath:
			args = append(args, pathParse(&body, byName[p.Name]))
		case lang.FromQuery:
			fmt.Fprintf(&body, "\t\tvolt%s, err := volt.QueryParam[%s](r, %q)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n", p.Name, p.GoType, p.Name)
			args = append(args, "volt"+p.Name)
		case lang.FromList:
			fmt.Fprintf(&body, "\t\tvolt%s, err := volt.QueryParams[%s](r, %q)\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n", p.Name, strings.TrimPrefix(p.GoType, "[]"), p.Name)
			args = append(args, "volt"+p.Name)
		case lang.FromBody:
			fmt.Fprintf(&body, "\t\tvar volt%s %s\n\t\tif err := volt.Decode(r, &volt%s); err != nil {\n\t\t\treturn err\n\t\t}\n", p.Name, p.GoType, p.Name)
			args = append(args, "volt"+p.Name)
		}
	}
	call := fmt.Sprintf("c.%s.%s(r.Context()%s)", q.Field, q.Method, prefixEach(args, ", "))
	if q.Result == "" {
		fmt.Fprintf(&body, "\t\tif err := %s; err != nil {\n\t\t\treturn err\n\t\t}\n", call)
		fmt.Fprintf(&body, "\t\treturn volt.RenderStatus(w, r, %d, nil)\n", q.Status)
		return body.String()
	}
	fmt.Fprintf(&body, "\t\tout, err := %s\n\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n", call)
	fmt.Fprintf(&body, "\t\treturn volt.RenderStatus(w, r, %d, out)\n", q.Status)
	return body.String()
}

func (g *generator) routeEmit(r *lang.RouteInfo) {
	pattern := fullPattern(r)
	eh := "nil"
	if r.ErrorHandler != "" {
		eh = "errHandler" + r.ErrorHandler
	}

	g.pf("\n\t// %s %s → %s", methodOrAny(r.Method), r.Spelled, handlerLabel(r))
	if len(r.Pipes) > 0 {
		g.pf(" [pipe: %s]", strings.Join(r.Pipes, ", "))
	}
	g.pf("\n")

	shim := fmt.Sprintf("volt.Handler(%q, func(w http.ResponseWriter, r *volt.Request) error {\n", pattern)
	if r.Query != nil {
		shim += queryShimBody(r)
		shim += fmt.Sprintf("\t}, %s)", eh)
	} else {
		var body strings.Builder
		call := make([]string, 0, len(r.Params))
		for _, p := range r.Params {
			call = append(call, pathParse(&body, p))
		}
		shim += body.String()
		shim += fmt.Sprintf("\t\treturn c.%s.%s(w, r%s)\n\t}, %s)", r.Controller, r.Action, prefixEach(call, ", "), eh)
	}

	if len(r.Pipes) > 0 {
		g.pf("\tmux.Handle(%q, %s(%s))\n", pattern, g.pipeVars[pipeKey(r.Pipes)], shim)
	} else {
		g.pf("\tmux.Handle(%q, %s)\n", pattern, shim)
	}
}

/* ===== volt_paths.go ===== */

func (g *generator) pathsEmit() error {
	named := false
	for _, r := range g.pkg.Routes {
		if r.HelperName != "" {
			named = true
			break
		}
	}
	// Every helper body references volt (URL at minimum); with no named
	// routes the import would be unused and the file uncompilable.
	if named {
		g.header(voltImport)
	} else {
		g.header()
	}

	emitted := false
	for _, r := range g.pkg.Routes {
		if r.HelperName == "" {
			continue
		}
		emitted = true
		g.pf("// Path%s returns the path for %s %s (%s).\n",
			r.HelperName, methodOrAny(r.Method), r.Spelled, handlerLabel(r))
		g.pf("func Path%s(%sopts ...volt.URLOption) string {\n", r.HelperName, sigParamsLead(r.Params))
		g.pf("\treturn volt.URL(%s, opts...)\n", pathExpr(r))
		g.pf("}\n\n")
	}
	if !emitted {
		g.pf("// No named routes: nothing to reverse.\n")
	}
	return nil
}

// sigParamsLead renders "id int32, " — leading form for paths funcs.
func sigParamsLead(ps []lang.Param) string {
	var b strings.Builder
	for _, p := range ps {
		b.WriteString(p.GoName + " " + p.Type.GoType() + ", ")
	}
	return b.String()
}

// pathExpr builds the Go expression producing the route's path from its
// typed arguments, e.g. `"/users/" + volt.SegInt(int64(id))`.
func pathExpr(r *lang.RouteInfo) string {
	if r.Pattern == "/{$}" {
		return `"/"`
	}
	var parts []string
	lit := ""
	flushLit := func() {
		if lit != "" {
			parts = append(parts, fmt.Sprintf("%q", lit))
			lit = ""
		}
	}
	byName := map[string]lang.Param{}
	for _, p := range r.Params {
		byName[p.Name] = p
	}
	for _, seg := range strings.Split(strings.TrimPrefix(r.Pattern, "/"), "/") {
		switch {
		case strings.HasPrefix(seg, "{"):
			name := strings.TrimSuffix(strings.TrimPrefix(seg, "{"), "}")
			name = strings.TrimSuffix(name, "...")
			p := byName[name]
			lit += "/"
			flushLit()
			switch {
			case p.Wild:
				parts = append(parts, "volt.SegWild("+p.GoName+")")
			case p.Type == lang.TString:
				parts = append(parts, "volt.Seg("+p.GoName+")")
			case p.Type == lang.TInt64:
				parts = append(parts, "volt.SegInt("+p.GoName+")")
			default:
				parts = append(parts, "volt.SegInt(int64("+p.GoName+"))")
			}
		default:
			lit += "/" + seg
		}
	}
	flushLit()
	return strings.Join(parts, " + ")
}

/* ===== volt_routes.go ===== */

func (g *generator) routesEmit() error {
	g.header(voltImport)

	g.pf("// Table lists every route of the package, in declaration order:\n")
	g.pf("// the routing DSL as introspectable data ('volt routes', metrics\n")
	g.pf("// labels, and downstream derivations read this).\n")
	g.pf("var Table = []volt.Route{\n")
	for _, r := range g.pkg.Routes {
		if r.Query != nil {
			g.pf("\t{Method: %q, Pattern: %q, Spelled: %q, Query: %q",
				r.Method, r.Pattern, r.Spelled, r.Query.Ref())
		} else {
			g.pf("\t{Method: %q, Pattern: %q, Spelled: %q, Controller: %q, Action: %q",
				r.Method, r.Pattern, r.Spelled, r.Controller, r.Action)
		}
		if r.HelperName != "" {
			g.pf(", Helper: %q", "Path"+r.HelperName)
		}
		if len(r.Params) > 0 {
			g.pf(", Params: []volt.RouteParam{")
			for i, p := range r.Params {
				if i > 0 {
					g.pf(", ")
				}
				g.pf("{Name: %q, Type: %q", p.Name, p.Type)
				if p.Wild {
					g.pf(", Wild: true")
				}
				g.pf("}")
			}
			g.pf("}")
		}
		g.pf("},\n")
	}
	g.pf("}\n")
	return nil
}

func methodOrAny(m string) string {
	if m == "" {
		return "any"
	}
	return m
}

/* ===== client/volt_client.go (§V4.10) ===== */

// clientEmit renders the client package: one typed method per query
// route, one raw method per named controller route, over the runtime's
// volt.Client. It imports the data packages and the runtime only.
func (g *generator) clientEmit() error {
	// Imports follow the methods: context for any method, net/http for
	// raw ones; a package with no client method at all still compiles.
	var imports []string
	anyMethod, rawMethod := false, false
	for _, r := range g.pkg.Routes {
		if r.ClientName == "" {
			continue
		}
		anyMethod = true
		if r.Query == nil {
			rawMethod = true
		}
	}
	if anyMethod {
		imports = append(imports, "context")
	}
	if rawMethod {
		imports = append(imports, "net/http")
	}
	imports = append(imports, "", voltImport)
	for _, q := range g.dataPackages() {
		imports = append(imports, dataImport(q))
	}
	doc := "// Package client calls the routes of package " + g.pkg.Name + " over HTTP\n" +
		"// (spec §V4.10): one typed method per query route, one raw method per\n" +
		"// named controller route. It imports the data packages and the volt\n" +
		"// runtime only, never the server.\n"
	g.headerFor("client", doc, imports...)

	g.pf("// Client calls package %s at Base. The embedded volt.Client carries\n", g.pkg.Name)
	g.pf("// the http.Client and the wire format (JSON by default, or GOB).\n")
	g.pf("type Client struct {\n\tvolt.Client\n}\n\n")
	g.pf("// New returns a client for the server at base, e.g. \"http://localhost:8888\".\n")
	g.pf("func New(base string) *Client {\n\treturn &Client{volt.Client{Base: base}}\n}\n\n")

	for _, r := range g.pkg.Routes {
		if r.ClientName == "" {
			continue
		}
		method := r.Method
		if method == "" {
			method = "GET" // the any-verb: the client speaks GET
		}
		if r.Query == nil {
			g.pf("// %s calls %s %s (%s); the response is the caller's to read and close.\n",
				r.ClientName, methodOrAny(r.Method), r.Spelled, handlerLabel(r))
			g.pf("func (c *Client) %s(ctx context.Context%s) (*http.Response, error) {\n", r.ClientName, sigParams(r.Params))
			g.pf("\treturn c.Raw(ctx, %q, volt.URL(%s))\n}\n\n", method, pathExpr(r))
			continue
		}
		q := r.Query
		var sig, body strings.Builder
		var opts []string
		var arg string
		for _, p := range q.Params {
			goType := p.GoType
			fmt.Fprintf(&sig, ", %s %s", p.Name, goType)
			switch p.Source {
			case lang.FromQuery:
				opts = append(opts, fmt.Sprintf("volt.Query(%q, volt.FormatQuery(%s))", p.Name, p.Name))
			case lang.FromList:
				fmt.Fprintf(&body, "\tfor _, v := range %s {\n\t\tq = append(q, volt.Query(%q, volt.FormatQuery(v)))\n\t}\n", p.Name, p.Name)
			case lang.FromBody:
				arg = p.Name
			}
		}
		url := "volt.URL(" + pathExpr(r) + ")"
		if len(opts) > 0 || body.Len() > 0 {
			// Scalar query parameters seed the option list; list
			// parameters append to it in the loops rendered above.
			loops := body.String()
			body.Reset()
			fmt.Fprintf(&body, "\tq := []volt.URLOption{%s}\n%s", strings.Join(opts, ", "), loops)
			url = "volt.URL(" + pathExpr(r) + ", q...)"
		}
		in := "nil"
		if arg != "" {
			in = arg
		}
		result := ""
		if q.Result != "" {
			result = q.Qualifier + "." + q.Result
			if q.Many {
				result = "[]" + result
			}
		}
		g.pf("// %s calls %s %s (%s).\n", r.ClientName, methodOrAny(r.Method), r.Spelled, q.Ref())
		if result == "" {
			g.pf("func (c *Client) %s(ctx context.Context%s) error {\n", r.ClientName, sig.String())
			g.pf("%s", body.String())
			g.pf("\treturn c.Do(ctx, %q, %s, %s, nil)\n}\n\n", method, url, in)
			continue
		}
		g.pf("func (c *Client) %s(ctx context.Context%s) (%s, error) {\n", r.ClientName, sig.String(), result)
		g.pf("%s", body.String())
		g.pf("\tvar out %s\n", result)
		g.pf("\terr := c.Do(ctx, %q, %s, %s, &out)\n\treturn out, err\n}\n\n", method, url, in)
	}
	return nil
}
