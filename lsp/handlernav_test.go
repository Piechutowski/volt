// TestHandlerRenameRewritesEveryRoute proves a rename at an action
// (editor.md, Go references): every route naming Pages.Ping is
// rewritten, the other actions of Pages are not, and the Go side is
// gopls's to rename.
func TestHandlerRenameRewritesEveryRoute(t *testing.T) {
	src := "package app\n\nscope / {\n\tget /ping Pages.Ping\n\tpost /ping Pages.Ping\n\tget /about Pages.About\n}\n"
	root := voltProject(t, map[string]string{
		"go.mod":          "module handlers\n",
		"app/routes.volt": src,
		"app/pages.go":    handlerGo,
	})
	d := NewDocument("file://"+filepath.Join(root, "app", "routes.volt"), src)
	edit, err := d.Rename(posOf(t, src, "Ping", 1), "Pong")
	if err != nil || edit == nil {
		t.Fatalf("rename = %v, %v", edit, err)
	}
	n := 0
	for _, edits := range edit.Changes {
		for _, e := range edits {
			if e.NewText != "Pong" {
				t.Errorf("edit %+v", e)
			}
			n++
		}
	}
	if n != 2 {
		t.Fatalf("rename of Pages.Ping made %d edits; want the two routes", n)
	}
}
