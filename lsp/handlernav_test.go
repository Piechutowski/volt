// TestHandlerDefinitionPrefersTheControllersName proves the tie-break
// (editor.md, Go references): when several types declare every action,
// the type named as the controller is the implementation, through a
// pointer receiver too.
func TestHandlerDefinitionPrefersTheControllersName(t *testing.T) {
	src := "package app\n\nscope / {\n\tget /ping Pages.Ping\n}\n"
	root := voltProject(t, map[string]string{
		"go.mod":          "module handlers\n",
		"app/routes.volt": src,
		"app/pages.go":    "package app\n\nimport \"github.com/Piechutowski/volt\"\n\ntype Other struct{}\n\nfunc (Other) Ping(r volt.Request) volt.Response { return volt.NoContent() }\n\ntype Pages struct{}\n\nfunc (*Pages) Ping(r volt.Request) volt.Response { return volt.NoContent() }\n",
	})
	d := NewDocument("file://"+filepath.Join(root, "app", "routes.volt"), src)
	loc := d.Definition(posOf(t, src, "Ping", 0))
	if loc == nil || loc.Range.Start.Line != 10 {
		t.Fatalf("definition with Other and *Pages declaring Ping = %+v; want the method of Pages on line 10", loc)
	}
}

// TestHandlerDefinitionWithoutAnImplementation proves the fallback
// (editor.md, Go references): with no implementing type in the package
// the action lands on the generated interface's method, and with no
// generated file either there is no definition and the hover says why.
func TestHandlerDefinitionWithoutAnImplementation(t *testing.T) {
	d := handlerDoc(t, true)
	loc := d.Definition(posOf(t, handlerRoutes, "Dashboard", 0))
	if loc == nil || !strings.HasSuffix(loc.URI, "app/volt_handlers.go") || loc.Range.Start.Line != 16 {
		t.Fatalf("definition of Admin.Dashboard = %+v; want AdminController's Dashboard on volt_handlers.go line 16", loc)
	}
	loc = d.Definition(posOf(t, handlerRoutes, "Admin", 0))
	if loc == nil || loc.Range.Start.Line != 15 {
		t.Fatalf("definition of the controller Admin = %+v; want AdminController on line 15", loc)
	}
	h := d.Hover(posOf(t, handlerRoutes, "Dashboard", 0))
	if h == nil || !strings.Contains(h.Contents.Value, "Dashboard(r volt.Request) volt.Response") || !strings.Contains(h.Contents.Value, "AdminController") {
		t.Fatalf("hover on Admin.Dashboard = %v; want the interface method", h)
	}
	bare := handlerDoc(t, false)
	if loc := bare.Definition(posOf(t, handlerRoutes, "Dashboard", 0)); loc != nil {
		t.Fatalf("definition of Admin.Dashboard with nothing generated = %+v; want none", loc)
	}
	if h := bare.Hover(posOf(t, handlerRoutes, "Admin", 0)); h == nil || !strings.Contains(h.Contents.Value, "no type in package") {
		t.Fatalf("hover on Admin with nothing generated = %v; want the reason", h)
	}
}

