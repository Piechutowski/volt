const handlerRoutes = "package app\n\nscope / [error_handler: Errors] {\n\tget /ping Pages.Ping\n\tget /about Pages.About\n\tget /posts Posts.Index\n\tget /feed Feed.Rss\n\tget /admin Admin.Dashboard\n\tget /events volt.Events\n}\n"

const handlerGo = "package app\n\nimport \"github.com/Piechutowski/volt\"\n\n" +
	"// Pages answers the static pages.\ntype Pages struct{}\n\n" +
	"// Ping answers pong.\nfunc (Pages) Ping(r volt.Request) volt.Response { return volt.NoContent() }\n\n" +
	"func (Pages) About(r volt.Request) volt.Response { return volt.NoContent() }\n\n" +
	"type posts struct{}\n\nfunc (posts) Index(r volt.Request) volt.Response { return volt.NoContent() }\n\n" +
	"type archive struct{}\n\nfunc (archive) Index(r volt.Request) volt.Response { return volt.NoContent() }\n\n" +
	"func Errors(r volt.Request, err error) volt.Response { return volt.NoContent() }\n\n" +
	"type feed struct{}\n\nfunc (feed) Rss(r volt.Request) volt.Response { return volt.NoContent() }\n"

const handlerGenerated = "// Code generated by volt gen from package app. DO NOT EDIT.\n\npackage app\n\nimport \"github.com/Piechutowski/volt\"\n\n" +
	"type PagesController interface {\n\tAbout(r volt.Request) volt.Response\n\tPing(r volt.Request) volt.Response\n}\n\n" +
	"type PostsController interface {\n\tIndex(r volt.Request) volt.Response\n}\n\n" +
	"type AdminController interface {\n\tDashboard(r volt.Request) volt.Response\n}\n\n" +
	"type FeedController interface {\n\tRss(r volt.Request) volt.Response\n}\n"

func handlerDoc(t *testing.T, generated bool) *Document {
	t.Helper()
	files := map[string]string{
		"go.mod":          "module handlers\n",
		"app/routes.volt": handlerRoutes,
		"app/pages.go":    handlerGo,
	}
	if generated {
		files["app/volt_handlers.go"] = handlerGenerated
	}
	root := voltProject(t, files)
	return NewDocument("file://"+filepath.Join(root, "app", "routes.volt"), handlerRoutes)
}

// TestHandlerDefinitionLandsOnTheMethod proves handler navigation
// (editor.md, Go references): the action of a route lands on the method
// of the one type in the package that declares every action of its
// controller, the controller on that type, and the action hovers with
// the method's signature and doc comment.
func TestHandlerDefinitionLandsOnTheMethod(t *testing.T) {
	d := handlerDoc(t, true)
	loc := d.Definition(posOf(t, handlerRoutes, "Ping", 0))
	if loc == nil || !strings.HasSuffix(loc.URI, "app/pages.go") || loc.Range.Start.Line != 8 || loc.Range.Start.Character != 13 {
		t.Fatalf("definition of Pages.Ping = %+v; want pages.go line 8 char 13", loc)
	}
	loc = d.Definition(posOf(t, handlerRoutes, "Pages", 0))
	if loc == nil || !strings.HasSuffix(loc.URI, "app/pages.go") || loc.Range.Start.Line != 5 {
		t.Fatalf("definition of the controller Pages = %+v; want the type on pages.go line 5", loc)
	}
	h := d.Hover(posOf(t, handlerRoutes, "Ping", 0))
	if h == nil || !strings.Contains(h.Contents.Value, "func (Pages) Ping(r volt.Request) volt.Response") || !strings.Contains(h.Contents.Value, "Ping answers pong.") {
		t.Fatalf("hover on Pages.Ping = %v; want the signature and the doc comment", h)
	}
}

